# 第 4 题：1 到 100 的累加与奇偶统计
#   【思路】
#     用一个 total 累加和，两个计数器 even_count / odd_count。
#     循环体里判断 n % 2 == 0 决定加到哪里。
#     range(1, 101) 生成 1..100。
# ============================================================
print("-" * 60)
print("第 4 题：累加与奇偶统计")
print("-" * 60)
print("【思路】range(1, 101) 遍历，用 % 2 判断奇偶，分别累加和计数")

total = 0
even_count = 0
odd_count = 0

for n in range(1, 101):
    total += n
    if n % 2 == 0:
        even_count += 1
    else:
        odd_count += 1

print(f"1 到 100 的和 = {total}")
print(f"偶数 {even_count} 个，奇数 {odd_count} 个")
print()


# ============================================================
# 第 5 题：数字各位之和
#   【思路】
#     n % 10 拿到最后一位，n // 10 把最后一位丢掉。
#     循环到 n 变成 0 就结束。
#     注意用一个临时变量 n，不要改掉原来的 number。
#     9875 -> 取 5，剩 987 -> 取 7，剩 98 -> 取 8，剩 9 -> 取 9，剩 0
# ============================================================
print("-" * 60)
print("第 5 题：数字各位之和")
print("-" * 60)
print("【思路】循环做两件事：n % 10 取末位累加，n // 10 去掉末位")

number = 9875
n = number          # 用临时变量，保住原值
digit_sum = 0
steps = []          # 记录每一轮取出的数字，方便演示过程

while n > 0:
    last = n % 10       # 取出最后一位
    digit_sum += last
    steps.append(last)
    n = n // 10         # 丢掉最后一位（这行千万别忘，否则死循环）

print(f"拆解过程：{' + '.join(str(x) for x in steps)}")
print(f"{number} 的各位数字之和 = {digit_sum}")
print()


