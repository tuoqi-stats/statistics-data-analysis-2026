# 第 1 题：BMI 计算器
#   【思路】
#     1. 字符串 "1.75" 不能直接算，先用 float() 转成浮点数；
#     2. BMI 公式是 体重 / 身高²，平方用 ** 2；
#     3. f"{值:.2f}" 表示保留两位小数。
# ============================================================
print("-" * 60)
print("第 1 题：BMI 计算器")
print("-" * 60)
print("【思路】先 float() 转换，再用 ** 求平方，最后 f-string 保留 2 位小数")

height = "1.75"
weight = "68"

height = float(height)          # "1.75" -> 1.75
weight = float(weight)          # "68"   -> 68.0

bmi = weight / (height ** 2)    # 68.0 / (1.75 * 1.75)
print(f"小明的 BMI = {bmi:.2f}")
