# ============================================================
# 第 3 题：位运算与逻辑运算
#   【思路】
#     12 = 0b1100，10 = 0b1010
#     & 按位与：都为 1 才是 1   -> 0b1000 = 8
#     | 按位或：有一个 1 就是 1 -> 0b1110 = 14
#     ^ 按位异或：不同才为 1   -> 0b0110 = 6
#     bin(x) 把整数转成 "0b..." 形式的二进制字符串。
# ============================================================
print("-" * 60)
print("第 3 题：位运算与逻辑运算")
print("-" * 60)
print("【思路】先把两个数写成二进制，再逐位比较")

a = 12   # 0b1100
b = 10   # 0b1010

print(f"a = {a} ({bin(a)}), b = {b} ({bin(b)})")
print()
print(f"a & b = {a & b} (二进制 {bin(a & b)})")     # 8  0b1000
print(f"a | b = {a | b} (二进制 {bin(a | b)})")     # 14 0b1110
print(f"a ^ b = {a ^ b} (二进制 {bin(a ^ b)})")     # 6  0b0110
print()
print("逻辑运算部分：")
