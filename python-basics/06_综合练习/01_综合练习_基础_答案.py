# 第 7 题：带默认参数的打招呼函数
#   【思路】
#     def greet(name, greeting="你好"):
#         return f"{greeting}，{name}！"
#     默认参数在"不传"的时候生效，传了就用传进来的值覆盖。
#     return 和 print 的区别：return 把结果交回调用处，print 只是显示。
# ============================================================
print("-" * 60)
print("第 7 题：带默认参数的打招呼函数")
print("-" * 60)
print("【思路】默认参数写在后面；用 return 交回结果，由调用处决定怎么用")


def greet(name, greeting="你好"):
    """返回一句问候语。greeting 不传时默认是"你好"。"""
    return f"{greeting}，{name}！"


print(greet("小明"))            # 用默认 greeting
print(greet("Tom", "Hello"))    # 覆盖默认 greeting

# 演示 return 的好处：结果可以继续参与运算，而 print 不行
msg = greet("小美")
print(f"这句话的长度是 {len(msg)} 个字符（说明 return 的结果能继续用）")
print()


# ============================================================
# 第 8 题：条件表达式 + 推导式 + 字符串切片
#   【思路】
#     1. 嵌套条件表达式（从右往左读）：
#          'A' if s >= 90 else ('B' if s >= 60 else 'C')
#     2. 脱敏：name[0] 保留首字，"*" * (len(name) - 1) 补齐星号
#     3. zip() 把四个列表按位置拉成一行行，再格式化输出
# ============================================================
print("-" * 60)
print("第 8 题：条件表达式 + 推导式 + 字符串切片")
print("-" * 60)
print("【思路】条件表达式定等级，推导式做脱敏，zip() 拉平四列一起打印")

names = ["李明", "王小雨", "张一", "诸葛亮"]
scores = [88, 59, 92, 45]

# 1. 条件表达式（嵌套）生成等级列表
levels = ['A' if s >= 90 else ('B' if s >= 60 else 'C') for s in scores]
print(f"等级列表 levels = {levels}")

# 2. 列表推导式生成脱敏名字
masked = [name[0] + "*" * (len(name) - 1) for name in names]
print(f"脱敏列表 masked = {masked}")

# 3. 配对打印
print()
print("姓名脱敏     分数   等级")
print("-" * 32)
for name, mask, score, level in zip(names, masked, scores, levels):
    print(f"{name:<6} {mask:<6} {score:>5}   {level}")

# 顺带统计一下各等级人数，用到字典 + 推导式
print()
level_count = {lv: levels.count(lv) for lv in ['A', 'B', 'C']}
print(f"等级分布：{level_count}")
print()


