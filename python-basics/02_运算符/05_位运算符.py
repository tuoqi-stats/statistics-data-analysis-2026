# -*- coding: utf-8 -*-
"""
05_位运算符.py —— 本章第 5 个示例文件

本节学什么：
    1. 什么是"二进制位"，为什么会有位运算
    2. 六个位运算符：&  |  ^  ~  <<  >>
    3. & 按位与、| 按位或、^ 按位异或、~ 按位取反
    4. << 左移、>> 右移（等价于乘除 2 的幂）
    5. ⚠️ 负数在内存里是"补码"，位运算碰到负数要格外小心
    6. 位运算的实用场景：判断奇偶、权限开关、标志位

运行方式（在 VSCode 终端里）：
    python 05_位运算符.py

预计输出：
    若干行二进制字符串和十进制数字，共 86 行左右，
    全程无报错、无等待输入。

💡 学习建议（重要）：
    零基础的话，你**不需要背下所有位运算细节**，
    只要知道：① 它们存在；② 是二进制层面的操作；
    ③ & | 常用于权限掩码；④ << >> 相当于乘除 2 的幂。
    真正写代码时用得不多，看代码时认得出来就够了。

阅读方法：
    本文件用 bin() 把数字显示成二进制，方便你一行行对照看。
"""

# ============================================================
# ===== 一、先搞懂：数字在内存里是"二进制" =====
# ============================================================
# 我们平时用的是十进制（0~9），计算机内部只认二进制（0 和 1）。
# 位运算就是**直接在这些 0/1 上操作**，所以速度极快。
#
# 用 bin() 可以把数字显示成二进制，前面带 '0b' 表示"这是二进制"。
# 用 0b 开头的字面量可以直接写二进制数，比如 0b1010 就是十进制的 10。

print("===== 一、认识二进制 =====")

# 十进制的 5 和 3 的二进制表示
print(bin(5))          # 预期输出：0b101       （从右往左：1×1 + 0×2 + 1×4 = 5）
print(bin(3))          # 预期输出：0b11        （1×1 + 1×2 = 3）
print(bin(10))         # 预期输出：0b1010
print(bin(0))          # 预期输出：0b0
print(bin(255))        # 预期输出：0b11111111

# 反过来，用 0b 前缀可以直接写二进制数
print(0b1010)          # 预期输出：10
print(0b11111111)      # 预期输出：255

# 💡 小知识：oct() 是八进制（0o 前缀），hex() 是十六进制（0x 前缀）
print(bin(255), oct(255), hex(255))     # 预期输出：0b11111111 0o377 0xff

# 为了便于阅读，下面每段都用"二进制对齐"的方式演示。
# 5 = 0101，3 = 0011（补齐到 4 位），这样逐位看得清楚。


# ============================================================
# ===== 二、& 按位与：两个都是 1 才是 1 =====
# ============================================================
# 规则：1 & 1 = 1，其他情况都是 0（只要有一位是 0，结果那位就是 0）。
#
#   5 = 0101
#   3 = 0011
#   ---------- 逐位 &
#   1 = 0001
#
# 💡 类比：& 像"两个开关串联"，都打开才通电。

print("\n===== 二、& 按位与 =====")

print(5 & 3)           # 预期输出：1     （0101 & 0011 = 0001 = 1）
print(bin(5 & 3))      # 预期输出：0b1
print(6 & 3)           # 预期输出：2     （0110 & 0011 = 0010 = 2）
print(12 & 10)         # 预期输出：8     （1100 & 1010 = 1000 = 8）

# 💡 经典用途 1：判断奇偶。任何数与 1 做 &，结果就是它的最低位
#    最低位是 1 → 奇数；是 0 → 偶数。比 % 运算还快。
print(7 & 1)           # 预期输出：1     → 7 是奇数
print(8 & 1)           # 预期输出：0     → 8 是偶数

# 💡 经典用途 2（最常用）：取出某些位（掩码 mask）
#    0b1111 只保留低 4 位，其他位全部清零
number = 0b11011010
print(bin(number))                    # 预期输出：0b11011010
print(bin(number & 0b1111))           # 预期输出：0b1010  （只留下了低 4 位）
print(bin(number & 0b11110000))       # 预期输出：0b11010000


# ============================================================
# ===== 三、| 按位或：有一个是 1 就是 1 =====
# ============================================================
# 规则：0 | 0 = 0，其他情况都是 1（只要有一位是 1，结果那位就是 1）。
#
#   5 = 0101
#   3 = 0011
#   ---------- 逐位 |
#   7 = 0111
#
# 💡 类比：| 像"两个开关并联"，任一打开就通电。

print("\n===== 三、| 按位或 =====")

print(5 | 3)           # 预期输出：7     （0101 | 0011 = 0111 = 7）
print(bin(5 | 3))      # 预期输出：0b111
print(6 | 3)           # 预期输出：7     （0110 | 0011 = 0111 = 7）
print(12 | 10)         # 预期输出：14    （1100 | 1010 = 1110 = 14）

# 💡 经典用途：打开指定的开关（置位）
flags = 0b0000
print(bin(flags | 0b0001))    # 预期输出：0b1     （打开第 0 号开关）
print(bin(flags | 0b0100))    # 预期输出：0b100   （打开第 2 号开关）


# ============================================================
# ===== 四、^ 按位异或：两个不一样才是 1 =====
# ============================================================
# 规则：相同为 0，不同为 1。（"异或"就是"不同才为真"）
#
#   5 = 0101
#   3 = 0011
#   ---------- 逐位 ^
#   6 = 0110
#
# ⚠️ 别忘了：^ 是异或，**不是乘方**！乘方是 **。
#
# 💡 异或的两个有趣性质：
#    ① a ^ a = 0        （自己和自己异或得 0）
#    ② a ^ 0 = a        （和 0 异或还是自己）
#    ③ 异或两次同一个数会还原，常用作简易加密

print("\n===== 四、^ 按位异或 =====")

print(5 ^ 3)           # 预期输出：6     （0101 ^ 0011 = 0110 = 6）
print(bin(5 ^ 3))      # 预期输出：0b110
print(6 ^ 3)           # 预期输出：5
print(12 ^ 10)         # 预期输出：6     （1100 ^ 1010 = 0110 = 6）

# 验证性质 ①②
print(5 ^ 5)           # 预期输出：0     （自己异或自己）
print(5 ^ 0)           # 预期输出：5     （和 0 异或）

# ⚠️ 再次强调：^ 不是乘方！
print(2 ^ 3)           # 预期输出：1     （异或的 10 ^ 11 = 01）
print(2 ** 3)          # 预期输出：8     （这才是 2 的 3 次方）

# 💡 经典玩法：不用临时变量也能交换两个数（了解即可，实际用 a, b = b, a 就好）
a, b = 5, 3
a = a ^ b
b = a ^ b
a = a ^ b
print(a, b)            # 预期输出：3 5


# ============================================================
# ===== 五、<< 左移与 >> 右移：整体搬动二进制位 =====
# ============================================================
# << 左移 n 位：所有位往左挪，右边补 0 —— 等价于 **乘以 2 的 n 次方**
# >> 右移 n 位：所有位往右挪，左边补 0 —— 等价于 **整除 2 的 n 次方**
#
#   5  = 0101
#   5 << 1 = 1010 = 10    （左移 1 位，相当于 ×2）
#   5 >> 1 = 0010 = 2     （右移 1 位，相当于 ÷2 取整）

print("\n===== 五、左移 << 与右移 >> =====")

# 左移
print(5 << 1)          # 预期输出：10    （5 × 2）
print(5 << 2)          # 预期输出：20    （5 × 4）
print(5 << 3)          # 预期输出：40    （5 × 8）
print(bin(5 << 2))     # 预期输出：0b10100

# 右移
print(20 >> 1)         # 预期输出：10    （20 ÷ 2）
print(20 >> 2)         # 预期输出：5     （20 ÷ 4）
print(7 >> 1)          # 预期输出：3     （7 ÷ 2 取整，和 7 // 2 一样）

# ⚠️ 注意：对正数来说 >> 和 // 结果一样，但对负数不一定（见第七节）

# 用乘法/整除验证"移位 = 乘除 2 的幂"
x = 13
print(x << 1 == x * 2)          # 预期输出：True
print(x << 2 == x * 4)          # 预期输出：True
print(x >> 1 == x // 2)         # 预期输出：True

# 💡 经典用途：快速构造 2 的幂（1 << n 就是 2 的 n 次方）
print(1 << 3)                   # 预期输出：8
print(1 << 10)                  # 预期输出：1024
print(1 << 0)                   # 预期输出：1


# ============================================================
# ===== 六、~ 按位取反：0 变 1、1 变 0 =====
# ============================================================
# ⚠️⚠️ 这是位运算里最容易搞错的一个，请仔细看。
#
# 公式：~x 等于 -(x + 1)。记住这个公式就能算对任何数：
#     ~5  = -(5 + 1)  = -6
#     ~0  = -(0 + 1)  = -1
#     ~-6 = -(-6 + 1) = 5
#
# 为什么？因为 Python 的整数是**任意精度**的，负数用「补码」表示，
# 而且没有固定位数（不像 C 语言的 int 只有 32 位）。
# 对 5（...000101）取反，会得到 ...111010，
# 这在补码里正好是 -6。所以 ~5 是 -6，**不是** 2，也不是 -5！

print("\n===== 六、~ 按位取反 =====")

print(~5)              # 预期输出：-6    （公式：-(5+1) = -6）
print(~0)              # 预期输出：-1    （公式：-(0+1) = -1）
print(~-6)             # 预期输出：5     （公式：-(-6+1) = 5）
print(~1)              # 预期输出：-2
print(~-1)             # 预期输出：0

# 用 bin() 看负数的二进制长什么样
# ⚠️ Python 里 bin(-6) 显示的是 '-0b110'，它把负号单独放在前面，
#    这只是"给人看的显示形式"，并不表示 -6 在内存里真的是 110。
#    真正的补码形式是无限位数的 ...11111010。
print(bin(-6))         # 预期输出：-0b110

# 验证 ~x == -(x+1) 这个公式对正数和负数都成立
x = 5
print(~x == -(x + 1))          # 预期输出：True
x = -6
print(~x == -(x + 1))          # 预期输出：True

# 💡 一个实用性质：~n 可以配合 & 做"清除某些位"
#    想清除低 1 位（把最低位变 0，也就是变成偶数）：
num = 7
print(num & ~1)                # 预期输出：6     （7 的二进制 111 & ...110 = 110）
print(6 & ~1)                  # 预期输出：6     （本来就是偶数，不变）


# ============================================================
# ===== 七、⚠️ 负数参与位运算要注意 =====
# ============================================================
# 负数的补码概念稍微复杂，这里只讲结论，够用即可：
#   ✓ 负数做 & | ^ ~ 时，直接按"公式/定义"理解结果，Python 给的一定对
#   ✓ 负数右移 >> 是"向下取整"，和 // 的规则一致（不是"砍掉小数"）
#   ⚠️ 千万别用"把负数的 bin() 字符串按位翻转"来理解取反，会得出错误结论

print("\n===== 七、负数与位运算 =====")

# -1 的补码（无限位）全都是 1，所以 -1 & 任何数 = 那个数
print(-1 & 5)          # 预期输出：5     （全 1 和 5 与 = 5）
print(-1 | 5)          # 预期输出：-1    （全 1 或任何数 = 全 1 = -1）

# -2 的补码是 ...11111110，和 1 做与运算取最低位
print(-2 & 1)          # 预期输出：0     → -2 是偶数（最低位是 0）
print(-3 & 1)          # 预期输出：1     → -3 是奇数（最低位是 1）

# 负数右移：向下取整，和整除 // 一致
print(-7 >> 1)         # 预期输出：-4
print(-7 // 2)         # 预期输出：-4    （两者相同！）
print(-7 >> 2)         # 预期输出：-2
print(-7 // 4)         # 预期输出：-2    （同样相同）

# ⚠️ 但左移在负数上的"乘 2"性质依然成立
print(-7 << 1)         # 预期输出：-14   （= -7 × 2）
print(-7 << 2)         # 预期输出：-28   （= -7 × 4）

# ✅ 结论：正负数的 & | ^ 结果都按位运算定义来，Python 不会算错；
#    唯一要记住的是 ~x = -(x+1)，以及负数右移是"向下取整"。


# ============================================================
# ===== 八、位运算的实战：用二进制位当"开关" =====
# ============================================================
# 场景：一个用户的权限可以用一个整数的每一位表示，好处是省内存、判断快。
# 这在系统编程、游戏存档、数据库标志位里非常常见。

print("\n===== 八、实战：权限开关 =====")

# 用不同位表示不同的权限（每个占一位，互不干扰）
PERM_READ = 0b0001    # 1  —— 读权限
PERM_WRITE = 0b0010   # 2  —— 写权限
PERM_EXEC = 0b0100    # 4  —— 执行权限

# 给用户授予"读 + 写"权限（用 | 打开开关）
user_perm = PERM_READ | PERM_WRITE
print(bin(user_perm))                     # 预期输出：0b11  （低两位是 1）

# 判断用户是否有"读"权限（用 & 取出那一位，结果为 0 就是没有）
print(user_perm & PERM_READ != 0)         # 预期输出：True
print(bool(user_perm & PERM_EXEC))        # 预期输出：False  （没有执行权限）

# 追加"执行"权限
user_perm |= PERM_EXEC                    # 等价于 user_perm = user_perm | PERM_EXEC
print(bin(user_perm))                     # 预期输出：0b111

# 撤销"写"权限（用 & ~ 把那一位清零）
user_perm &= ~PERM_WRITE                  # 等价于 user_perm = user_perm & ~PERM_WRITE
print(bin(user_perm))                     # 预期输出：0b101  （中间的 0 就是被撤销的写权限）

# 切换"写"权限（用 ^ 取反那一位：本来开着就关，本来关着就开）
user_perm ^= PERM_WRITE
print(bin(user_perm))                     # 预期输出：0b111

# 💡 位运算的优先级：<< >> 高于 &，& 高于 ^，^ 高于 |。
#    上面用到的 &= 之类都是复合赋值，含义和 += 一样。
#    实际工作中请**一律加括号**，可读性比省字符重要得多。


# ---------- 小结 ----------
# 1. 位运算直接在 0/1 上操作，速度快，但日常写业务代码用得不多。
# 2. & 全 1 才 1（取位/判断奇偶）；| 有 1 就 1（置位）；^ 不同为 1（翻转）。
# 3. ⚠️ ^ 是异或不是乘方，乘方是 **。
# 4. << 左移 = 乘 2 的幂；>> 右移 = 整除 2 的幂（对正数等价于 //）。
# 5. ⚠️ ~x 等于 -(x + 1)：~5 是 -6，~0 是 -1，~-6 是 5；bin(-6) 显示为 '-0b110'。
# 6. 负数位运算按补码规则来，Python 结果一定正确；负数 >> 是向下取整。
# 7. 实战套路：用 | 开权限、& 查权限、& ~ 撤销、^ 切换。
