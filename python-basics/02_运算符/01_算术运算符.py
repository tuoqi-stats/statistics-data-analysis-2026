# -*- coding: utf-8 -*-
"""
01_算术运算符.py —— 本章第 1 个示例文件

本节学什么：
    1. 七种算术运算符：+  -  *  /  //  %  **
    2. 整除 // 与取模 % 的区别（一个看"商"，一个看"余"）
    3. 除法 / 的结果永远是小数（float）
    4. 字符串、列表也能用 + 和 *（"加号重载"）
    5. 混合运算时 Python 会自动向上转型
    6. 运算符优先级：** > 一元负号 > * / // % > + -

运行方式（在 VSCode 终端里）：
    python 01_算术运算符.py

预计输出：
    每个小节都有若干行带说明的结果，共 70 行左右，
    全部为数字或字符串，不会有任何报错、也不会卡住等输入。

阅读方法：
    代码里每一行 print() 上方的注释，写的就是"这一行会输出什么"。
    先看注释猜结果，再运行对照，猜错了就重点琢磨那一行。
"""

# ============================================================
# ===== 一、加、减、乘、除：最熟悉的四个 =====
# ============================================================
# 四则运算和数学课上完全一样，运算符分别是 + - * / 。
# 注意：乘法用的是「星号 *」，不是字母 x，也不是小学数学里的「×」。

print("===== 一、加减乘除 =====")

# 两个整数相加
print(3 + 5)          # 预期输出：8

# 两个整数相减，结果可以是负数
print(3 - 5)          # 预期输出：-2

# 两个整数相乘
print(3 * 5)          # 预期输出：15

# ⚠️ 重点：Python 的除法 / 结果永远是小数（float），不会像 C 语言那样丢小数
# 只要用了 /，哪怕能整除，结果也带小数点
print(10 / 2)         # 预期输出：5.0    （注意是 5.0 不是 5）
print(7 / 2)          # 预期输出：3.5
print(1 / 3)          # 预期输出：0.3333333333333333（浮点数精度有限，后面会讲）

# 除法的结果类型可以直接查看
print(type(10 / 2))   # 预期输出：<class 'float'>
print(type(3 + 5))    # 预期输出：<class 'int'>  （加法不改变类型）

# 💡 生活类比：/ 就像用菜刀切西瓜，切完就是"几块半"，永远带零头
#    // 才是"够装几整箱"，只数完整的份数


# ============================================================
# ===== 二、整除 // ：只要商，"把小数部分直接砍掉" =====
# ============================================================
# // 叫「整除」或「地板除」，结果是「向下取整」后的商。
# ⚠️ 注意是"向下取整"，不是"砍掉小数"——对负数来说两者不一样！见下。

print("\n===== 二、整除 // =====")

# 正数整除：7 里面最多有 3 个完整的 2
print(7 // 2)         # 预期输出：3

# 能整除时，结果就是整数，不带小数点（这和 / 不同）
print(10 // 2)        # 预期输出：5    （对比上面 10 / 2 得 5.0）
print(type(10 // 2))  # 预期输出：<class 'int'>（两个整数整除得整数）

# ⚠️⚠️ 大陷阱：负数整除是"向下取整"，不是"砍掉小数"
# -7 / 2 = -3.5，向下取整 = -4（数轴上更靠左），而不是 -3
print(-7 // 2)        # 预期输出：-4     ← 不是 -3！

# 验证一下"向下取整"这个说法：// 的结果用数学函数 math.floor() 算出来一模一样
import math           # 只用到标准库，不依赖第三方包
print(math.floor(-7 / 2))  # 预期输出：-4  （和 -7 // 2 相同）
print(math.floor(7 / 2))   # 预期输出：3   （和 7 // 2 相同）

# 💡 记忆口诀：// 找的是"数轴上不超过结果的那个最大整数"


# ============================================================
# ===== 三、取模 % ：只要余数 =====
# ============================================================
# % 读作「取模」或「取余」，返回的是除法之后的余数。
# 整除 // 和取模 % 是一对好搭档，它们满足这个恒等式：
#       a == (a // b) * b + (a % b)
# 也就是说：被除数 = 商 × 除数 + 余数

print("\n===== 三、取模 % =====")

print(7 % 2)          # 预期输出：1    （7 = 2*3 + 1，余 1）
print(10 % 2)         # 预期输出：0    （整除时余数是 0）
print(10 % 3)         # 预期输出：1    （10 = 3*3 + 1）

# 用恒等式验证一下上面的结论
print((7 // 2) * 2 + (7 % 2))    # 预期输出：7    （还原回被除数）
print((10 // 3) * 3 + (10 % 3))  # 预期输出：10

# ⚠️ 负数的取模结果永远是"正数或 0"（Python 的规则），符号跟着除数走
# -7 = 2 * (-4) + 1，所以余数是 1
print(-7 % 2)         # 预期输出：1     ← 不是 -1！
print(7 % -2)         # 预期输出：-1    （符号跟着除数 -2 走）

# 💡 取模最常见的两大用途：
#    1) 判断奇偶： n % 2 == 0 就是偶数
print(8 % 2)          # 预期输出：0   → 8 是偶数
print(9 % 2)          # 预期输出：1   → 9 是奇数
#    2) 判断倍数： n % 3 == 0 就是 3 的倍数
print(12 % 3)         # 预期输出：0   → 12 是 3 的倍数


# ============================================================
# ===== 四、幂运算 ** ：乘方 =====
# ============================================================
# ** 表示"多少次方"，a ** b 就是 a 的 b 次方。
# ⚠️ 不要写成 ^！在 Python 里 ^ 是位运算符（异或），不是乘方，详见 05_位运算符.py

print("\n===== 四、幂运算 ** =====")

print(2 ** 3)         # 预期输出：8     （2 的 3 次方）
print(5 ** 2)         # 预期输出：25    （5 的平方）
print(2 ** 10)        # 预期输出：1024

# 指数可以是 0、负数、小数
print(2 ** 0)         # 预期输出：1     （任何数的 0 次方都是 1）
print(2 ** -1)        # 预期输出：0.5   （负指数 = 倒数）
print(9 ** 0.5)       # 预期输出：3.0   （0.5 次方 = 开平方）

# ⚠️ Python 的整数是「任意精度」的，不会像 C 语言那样溢出！
# 2 的 100 次方是一个超长整数，照样精确输出
print(2 ** 100)       # 预期输出：1267650600228229401496703205376（31 位数）

# 💡 陷阱对比：^ 不是乘方！这是新手最常犯的错之一
print(2 ^ 3)          # 预期输出：1     （这不是 8，而是位运算"异或"）


# ============================================================
# ===== 五、+ 和 * 还能用在字符串、列表上 =====
# ============================================================
# Python 的运算符是"看对象办事"的：
#   +  在数字间是加法，在字符串/列表间就是"拼接"
#   *  在数字间是乘法，在"字符串/列表 × 整数"时是"重复 N 次"

print("\n===== 五、+ 和 * 的其他用法 =====")

# 字符串拼接
print("Hello" + " " + "Python")        # 预期输出：Hello Python

# 字符串重复（只能和整数相乘）
print("-" * 20)                        # 预期输出：--------------------
print("Hi! " * 3)                      # 预期输出：Hi! Hi! Hi!

# 列表拼接与重复
print([1, 2] + [3, 4])                 # 预期输出：[1, 2, 3, 4]
print([0] * 5)                         # 预期输出：[0, 0, 0, 0, 0]

# ⚠️ 陷阱：字符串 + 数字会报错！类型必须一致
# print("年龄：" + 18)   # 这一行会 TypeError，所以先注释掉
# 正确做法一：用 str() 转换
print("年龄：" + str(18))              # 预期输出：年龄：18
# 正确做法二（后面章节会细讲）：用 f-string
age = 18
print(f"年龄：{age}")                  # 预期输出：年龄：18

# ⚠️ 陷阱：字符串没有"减法"和"除法"
# print("abc" - "a")    # TypeError
# print("abc" / 2)      # TypeError


# ============================================================
# ===== 六、混合运算：类型会自动"向上转型" =====
# ============================================================
# int（整数）和 float（小数）一起运算时，结果会自动变成 float，
# 因为 float 能表示的范围"更大"，这叫向上转型。

print("\n===== 六、混合运算与类型转换 =====")

print(1 + 2.0)              # 预期输出：3.0   （int + float = float）
print(type(1 + 2.0))        # 预期输出：<class 'float'>
print(3 * 1.5)              # 预期输出：4.5
print(10 // 3)              # 预期输出：3     （两个 int 整除还是 int）
print(10 // 3.0)            # 预期输出：3.0   （有一个 float，结果就是 float）
print(2 ** 3.0)             # 预期输出：8.0

# 💡 一个经典坑：浮点数不一定精确，0.1 + 0.2 不等于 0.3
print(0.1 + 0.2)            # 预期输出：0.30000000000000004
print(0.1 + 0.2 == 0.3)     # 预期输出：False   ← 因为浮点精度误差！
# 这是所有编程语言的通病（IEEE 754 标准），不是 Python 的 bug。
# 需要精确计算时用 round() 或 decimal 模块，后面章节会讲。


# ============================================================
# ===== 七、运算符优先级：谁先算？ =====
# ============================================================
# 就像"先乘除后加减"，Python 也有一套优先级规则。
# 算术运算符从高到低（先算的排前面）：
#
#   优先级 | 运算符        | 说明
#   -------|---------------|--------------------------
#     1    | ( )           | 括号，最高优先级
#     2    | **            | 幂运算
#     3    | +x  -x  ~x    | 一元正号 / 负号 / 按位取反
#     4    | *  /  //  %   | 乘、除、整除、取模
#     5    | +  -          | 加、减
#
# ⚠️ ** 是右结合的（从右往左算），其他算术运算符是左结合的。
# ⚠️ 强烈建议：拿不准就加括号！括号不花钱，能救命。

print("\n===== 七、运算符优先级 =====")

# 先乘后加：2 * 3 = 6，再 1 + 6 = 7
print(1 + 2 * 3)        # 预期输出：7

# 加括号改变顺序：先算 1 + 2 = 3，再 3 * 3 = 9
print((1 + 2) * 3)      # 预期输出：9

# ** 比 * 优先级高：先算 2**3 = 8，再 2 * 8 = 16
print(2 * 2 ** 3)       # 预期输出：16

# 幂运算右结合：2 ** (3 ** 2) = 2 ** 9 = 512（不是 (2**3)**2 = 64）
print(2 ** 3 ** 2)      # 预期输出：512
print((2 ** 3) ** 2)    # 预期输出：64   （加括号才是这个结果）

# 一元负号的优先级低于 **：-2 ** 2 相当于 -(2 ** 2) = -4
print(-2 ** 2)          # 预期输出：-4    ← 不是 4
print((-2) ** 2)        # 预期输出：4     （加括号才是 4）

# 整除、取模和乘除同级，从左往右算
print(20 // 3 % 2)      # 预期输出：0     （先 20//3=6，再 6%2=0）
print(2 + 10 // 3)      # 预期输出：5     （先 10//3=3，再 2+3=5）

# 💡 一个综合例子：算平均分
score1, score2, score3 = 88, 95, 76
print((score1 + score2 + score3) / 3)   # 预期输出：86.33333333333333


# ---------- 小结 ----------
# 1. + - * 就是加减乘；/ 的结果永远是 float，哪怕能整除。
# 2. // 是整除（向下取整），% 是取余，两者满足 a = (a//b)*b + (a%b)。
# 3. 负数整除要当心：-7 // 2 得到 -4，不是 -3（向下取整）。
# 4. ** 是乘方，^ 是位运算异或，千万别混用；Python 整数不溢出。
# 5. + 和 * 对字符串/列表另有含义：拼接与重复。
# 6. int 和 float 混算会自动变成 float；0.1 + 0.2 != 0.3 是浮点精度问题。
# 7. 优先级：** > 一元负号 > * / // % > + -；拿不准就加括号。
