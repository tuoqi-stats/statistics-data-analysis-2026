# ============================================================
# 第 1 题：算术运算符综合
# ============================================================
# 【思路】
#   把总秒数先按 3600 切成"小时"，剩下的再用 60 切成"分"和"秒"。
#   这正是 // 和 % 最经典的搭档用法：// 取份数，% 取剩余。
#
# 【考察点】// 与 % 的分工
# 【易错点】用 / 会得到小数；算分钟时忘记先减去小时占用的秒数

print("\n【第 1 题】")

total_seconds = 3725

hours = total_seconds // 3600         # 3725 // 3600 = 1，能装满 1 小时
remainder = total_seconds % 3600      # 3725 % 3600 = 125，剩下的秒数
minutes = remainder // 60             # 125 // 60 = 2，能装满 2 分钟
seconds = remainder % 60              # 125 % 60 = 5，最后剩下的秒数

print(f"{total_seconds} 秒 = {hours} 小时 {minutes} 分 {seconds} 秒")
# 预期输出：3725 秒 = 1 小时 2 分 5 秒

# 💡 更简洁的写法（链式继续除）：
m2, s2 = (total_seconds % 3600) // 60, (total_seconds % 3600) % 60
print(f"换个写法验证：{total_seconds // 3600} 小时 {m2} 分 {s2} 秒")
# 预期输出：换个写法验证：1 小时 2 分 5 秒


# ============================================================
# 第 2 题：判断奇偶与倍数
# ============================================================
# 【思路】
#   n % 2 的结果只有 0 或 1，为 0 就是偶数，为 1 就是奇数。
#   倍数判断同理：余数为 0 就说明能整除。
#
# 【考察点】% 的两种典型用途
# 【易错点】写成 n % 2 == 1 判断奇数虽然对正数成立，但用 != 0 更严谨

print("\n【第 2 题】")

n = 91

# 判断奇偶：余数为 0 是偶数，否则是奇数
if n % 2 == 0:
    print(f"{n} 是偶数")
else:
    print(f"{n} 是奇数")
# 预期输出：91 是奇数

print(f"{n} 是 3 的倍数: {n % 3 == 0}")
# 预期输出：91 是 3 的倍数: False

print(f"{n} 是 7 的倍数: {n % 7 == 0}")
# 预期输出：91 是 7 的倍数: True

# 💡 一行版本（不借助 if 的写法）：
print(f"用一行表达：{'偶数' if n % 2 == 0 else '奇数'}")
# 预期输出：用一行表达：奇数


# ============================================================
# 第 3 题：浮点数陷阱与四舍五入
# ============================================================
# 【思路】
#   0.1、0.2 在二进制里都是无限循环小数，存不进有限位，
#   相加时误差累积，结果就"差一点点"。
#   所以不能直接用 == 比，要么四舍五入后再比，要么判断差值足够小。
#
# ⚠️ 关于例题的选择（这一点很值得体会）：
#   并不是"任何浮点相加都会出错"。0.1 + 0.2 会得到 0.30000000000000004，
#   但 0.1 + 0.2 + 0.7 的误差刚好被抵消，结果正好是 1.0。
#   正因为它"有时对有时错"，浮点问题才格外隐蔽——
#   所以规矩是：**只要涉及浮点，就不要用 == 直接比。**
#
# 【考察点】浮点数精度问题与正确的比较方式
# 【易错点】直接用 == 比较浮点数；或者以为这只是 Python 的 bug

print("\n【第 3 题】")

# ---- 会出错的情况：0.1 + 0.2 ----
a, b = 0.1, 0.2
total = a + b

print(f"直接相加: {total}")
# 预期输出：直接相加: 0.30000000000000004

print(f"直接比较: {total == 0.3}")
# 预期输出：直接比较: False    ← 0.30000000000000004 不等于 0.3

# 方式一：四舍五入到 10 位小数再比（精度损失可控）
print(f"round 比较: {round(total, 10) == 0.3}")
# 预期输出：round 比较: True

# 方式二：判断"差的绝对值"是否小于一个极小值（工程上最常用）
print(f"差值比较: {abs(total - 0.3) < 1e-9}")
# 预期输出：差值比较: True

# ---- 再对比一个"看起来没问题"的情况 ----
total2 = 0.1 + 0.2 + 0.7
print(f"0.1 + 0.2 + 0.7 = {total2}，直接比 1.0: {total2 == 1.0}")
# 预期输出：0.1 + 0.2 + 0.7 = 1.0，直接比 1.0: True
# 💡 这里恰好对了，但别因此觉得"浮点比较可以用 =="，它随时可能翻脸。

# 💡 如果业务上要求严格精确（比如金额），应该用 decimal 模块：
from decimal import Decimal
print(f"Decimal 精确计算: {Decimal('0.1') + Decimal('0.2')}")
# 预期输出：Decimal 精确计算: 0.3


# ============================================================
# 第 4 题：逻辑运算符判断闰年
# ============================================================
# 【思路】
#   规则是两个条件的"或"：
#     条件A：能被 4 整除 且 不能被 100 整除
#     条件B：能被 400 整除
#   注意条件A 里的"且的否定"要用 != 而不是 not ==。
#
# 【考察点】and / or 组合，以及优先级需要括号
# 【易错点】忘记加括号导致优先级出错；把 1900 当成闰年

print("\n【第 4 题】")

def is_leap_year(year):
    """判断某一年是不是闰年：能被4整除且不能被100整除，或者能被400整除。"""
    return (year % 4 == 0 and year % 100 != 0) or (year % 400 == 0)

for year in (1900, 2000, 2024, 2023):
    print(f"{year} 是闰年: {is_leap_year(year)}")
# 预期输出：
#   1900 是闰年: False   （能被 4 和 100 整除，但不能被 400 整除）
#   2000 是闰年: True    （能被 400 整除）
#   2024 是闰年: True
#   2023 是闰年: False

# 💡 不用函数的一次性写法（练习题里这样写就够了）：
year1, year2 = 1900, 2000
print(f"1900 是闰年: {(year1 % 4 == 0 and year1 % 100 != 0) or (year1 % 400 == 0)}")
print(f"2000 是闰年: {(year2 % 4 == 0 and year2 % 100 != 0) or (year2 % 400 == 0)}")
# 预期输出：1900 是闰年: False / 2000 是闰年: True


# ============================================================
# 第 5 题：理解短路求值
# ============================================================
# 【思路】
#   and 从左往右算，遇到假值立刻停下。
#   把 "分母不为 0" 放在左边，就形成了一道"守门员"：
#   分母是 0 时短路发生，右边的除法压根不会被执行，自然不会报错。
#
# 【考察点】短路求值的实际价值（防错，不只是省计算）
# 【易错点】把条件顺序写反（除法写左边），那样还是会报错

print("\n【第 5 题】")

numerator = 10

# 测试一：分母为 0
denominator = 0
result = denominator != 0 and numerator / denominator > 1
print(f"分母为 0 时: {result}")
# 预期输出：分母为 0 时: False

# 测试二：分母为 4
denominator = 4
result = denominator != 0 and numerator / denominator > 1
print(f"分母为 4 时: {result}")
# 预期输出：分母为 4 时: True   （10/4 = 2.5 > 1）

# ⚠️ 对比：如果把 and 改成 or，会变成"短路保护失效"的反例：
# denominator = 0
# result = denominator != 0 or numerator / denominator > 1   # 报 ZeroDivisionError！
# 因为左边 False，or 必须继续算右边，除法就炸了。

# ✅ 结论：用 and 做前置校验，用 or 做兜底默认值，这是两种最典型的用法。


# ============================================================
# 第 6 题：and / or 返回操作数本身
# ============================================================
# 【思路】
#   or 返回第一个"真值"，所以 "" or "游客" 会返回 "游客"（空字符串是假）。
#   and 返回第一个"假值"，所以空列表会被原样返回（空列表是假）。
#   这样一行就能替代 if/else，是 Python 里很常见的惯用法。
#
# 【考察点】and / or 的返回值规则，真假值判断
# 【易错点】以为 and/or 一定返回 True/False

print("\n【第 6 题】")

# 任务①：空昵称就用默认值
user_nick = ""
nickname = user_nick or "游客"
print(nickname)
# 预期输出：游客

# 非空的情况也验证一下
nickname2 = "小明" or "游客"
print(nickname2)
# 预期输出：小明

# 任务②：购物车非空才拼接描述，为空则返回空列表本身
cart = ["苹果", "牛奶", "面包"]
result = cart and f"购物车共 {len(cart)} 件商品"
print(result)
# 预期输出：购物车共 3 件商品

# 空购物车的情况
empty_cart = []
result2 = empty_cart and f"购物车共 {len(empty_cart)} 件商品"
print(result2)
# 预期输出：[]     （返回的是空列表本身，不是字符串）

# ⚠️ 注意：这种写法虽然简洁，但如果"0"是合法值就会出问题：
count = 0
print(count or "没有数据")      # 预期输出：没有数据  ← 其实 0 条也是一种有效数据！
# ✅ 这种场合还是老老实实用 if 判断更安全：
print("没有数据" if count == 0 else f"{count} 条数据")   # 预期输出：没有数据


# ============================================================
# 第 7 题：复合赋值与累加
# ============================================================
# 【思路】
#   这是循环里最经典的两个"累积"模式：
#     累加 sum += x，初始值必须是 0（加法的单位元）
#     累乘 prod *= x，初始值必须是 1（乘法的单位元）
#
# 【考察点】+= 和 *= 的使用，以及初始值的选择
# 【易错点】累乘器初始化成 0，结果永远是 0

print("\n【第 7 题】")

# ① 求 1~10 的平方和
square_sum = 0                     # 累加器从 0 开始
for i in range(1, 11):             # range(1, 11) 是 1 到 10
    square_sum += i ** 2           # 每次把 i 的平方加进去
print(f"1~10 的平方和: {square_sum}")
# 预期输出：1~10 的平方和: 385

# ② 求 10 的阶乘
factorial = 1                      # ⚠️ 累乘器必须从 1 开始
for i in range(1, 11):
    factorial *= i                 # 每次乘以 i
print(f"10 的阶乘: {factorial}")
# 预期输出：10 的阶乘: 3628800

# 💡 顺便验证一下前面讲过的坑：累乘器从 0 开始会怎样
wrong = 0
for i in range(1, 11):
    wrong *= i
print(f"从 0 开始的累乘结果: {wrong}")
# 预期输出：从 0 开始的累乘结果: 0   ← 0 乘任何数都是 0


# ============================================================
# 第 8 题：列表的 += 陷阱
# ============================================================
# 【思路】
#   copy_list = original 只是给同一个列表多贴了一个名字，
#   两个名字指向的是"同一件东西"。
#   而列表的 += 是"原地修改"（相当于 extend），
#   所以改动会同时反映在两个名字上。
#   要真正的副本，必须用切片 [:]、list() 或 .copy()。
#
# 【考察点】赋值 ≠ 复制；列表 += 是原地修改
# 【易错点】以为 = 会复制一份数据

print("\n【第 8 题】")

original = [1, 2]

# ---- 有问题的写法（演示"牵连"现象）----
wrong_copy = original
wrong_copy += [3]
print("有问题的写法 —— original:", original)
# 预期输出：有问题的写法 —— original: [1, 2, 3]   ← 被牵连了！
print("有问题的写法 —— wrong_copy:", wrong_copy)
# 预期输出：有问题的写法 —— wrong_copy: [1, 2, 3]

# ---- 正确写法：先复制，再修改 ----
original = [1, 2]
copied = original[:]            # 用切片生成新列表（也可以写 list(original) 或 .copy()）
copied += [3]                   # 改的是新列表，original 不受影响
print("original:", original)
# 预期输出：original: [1, 2]
print("copied:", copied)
# 预期输出：copied: [1, 2, 3]

# 💡 为什么原来的写法会出错？
#    因为 copy_list = original 只是"又贴了一个名字"，
#    两个变量指向内存里的同一个列表；列表的 += 是在原列表上追加元素，
#    所以通过任何一个名字看到的都是被改过的那个列表。
# ✅ 记住：要复制可变对象，用 [:] / list() / .copy()；要"贴名字"才用 =。


# ============================================================
# 第 9 题：位运算实战——权限开关
# ============================================================
# 【思路】
#   把每一种权限放在一个单独的二进制位上，互不干扰。
#   然后：| 用来"打开"某位，& 用来"检查"某位，& ~ 用来"关闭"某位。
#
# 【考察点】| & ~ 的语义与 bin() 显示
# 【易错点】用 ^ 去"关闭"权限——^ 是切换，本来关着的会被打开

print("\n【第 9 题】")

READ = 0b001       # 读权限，十进制 1
WRITE = 0b010      # 写权限，十进制 2
EXECUTE = 0b100    # 执行权限，十进制 4

perms = READ

print(f"初始:          {bin(perms)}")
# 预期输出：初始:          0b1

perms |= WRITE                        # 用 | 把写权限那一位置 1
print(f"加上写权限:     {bin(perms)}")
# 预期输出：加上写权限:     0b11

print(f"有写权限吗:     {bool(perms & WRITE)}")
# 预期输出：有写权限吗:     True   （与运算结果非 0 就说明那一位是 1）

print(f"有执行权限吗:   {bool(perms & EXECUTE)}")
# 预期输出：有执行权限吗:   False

perms &= ~WRITE                       # 用 & ~ 把写权限那一位清 0
print(f"去掉写权限后:   {bin(perms)}")
# 预期输出：去掉写权限后:   0b1

# ⚠️ 对比：用 ^ 是"切换"，不能用来关闭
demo = READ
demo ^= WRITE                  # 本来没有写权限，异或后反而加上了
print(f"用 ^ 操作未开启的权限: {bin(demo)}")
# 预期输出：用 ^ 操作未开启的权限: 0b11   ← 权限被"切"回来了，不是原来的 0b1


# ============================================================
# 第 10 题：综合题——== 与 is 的正确选择
# ============================================================
# 【思路】
#   核心区别：== 比"值"，is 比"身份（是不是同一个对象）"。
#   除了 None / True / False 这类单例，其他一律用 ==。
#
# 【考察点】== 与 is 的适用场景
# 【易错点】用 is 比数字和字符串——小整数和短字符串可能"碰巧"是 True，
#          这让错误很难被发现（因为测试时是对的！）

print("\n【第 10 题】")

name = "admin"
result = None
flag = True
lst1 = [1, 2, 3]
lst2 = [1, 2, 3]

# ① 判断字符串相等 → 用 ==（比的是内容）
#    理由：字符串可能来自输入/拼接，is 的结果不可预测。
print(f'① name == "admin" → {name == "admin"}')
# 预期输出：① name == "admin" → True

# ② 判断 None → 用 is（None 全程序只有唯一一个，官方 PEP 8 推荐）
#    理由：is None 语义明确、速度更快，且不会被自定义的 __eq__ 干扰。
print(f"② result is None → {result is None}")
# 预期输出：② result is None → True

# ③ 判断数字相等 → 用 ==
#    理由：数字是"值类型"，你要的永远是"数值相等"。
#          is 的结果取决于对象有没有被复用，非常不可靠。
big1, big2 = 1000, 1000
print(f"③ 1000 == 1000 → {big1 == big2}")
# 预期输出：③ 1000 == 1000 → True

# ⚠️ 下面这个才是 is 比数字真正翻车的地方：用"运行时才产生"的大整数
#    注意必须让值在运行时才算出来（比如从字符串转换），
#    否则 Python 会在编译期就把 999+1 折叠成常量 1000，两者又会变成同一个对象。
calc1 = int("1000")    # 运行时从字符串转换而来
calc2 = 500 * 2        # 直接写的算式会被编译器折叠成常量 1000
print(f"③ 补充：int('1000') is 1000 → {calc1 is calc2}")
# 预期输出：③ 补充：int('1000') is 1000 → False   ← 两个不同的对象！
print(f"③ 补充：但它们的值相等 → {calc1 == calc2}")
# 预期输出：③ 补充：但它们的值相等 → True

# 💡 有意思的是：直接写字面量 1000 和 1000 时，Python 会把同一个代码块里
#    相同的常量合并成一个对象，所以 is 反而是 True；
#    而 int("1000") 是在运行时新建的对象，is 就是 False。
#    **同一个"值"，is 的结果却不一样 —— 这就是绝不能拿 is 比数字的原因。**
#    （另外，写成字面量 1000 is 1000 时 Python 会给出 SyntaxWarning 提醒你改用 ==，
#      这说明语言层面就认为"用 is 比整数"是个错误。）

# ④ 判断布尔值 → 用 is（True/False 也是单例）
#    理由：和 None 一样，它们全局唯一，语义清晰。
print(f"④ flag is True → {flag is True}")
# 预期输出：④ flag is True → True

# ⑤ 判断列表内容相同 → 用 ==（列表是可变对象，is 一定是 False，除非同一个对象）
#    理由：我们要的是"内容一样"，那就是 == 的工作。
print(f"⑤ lst1 == lst2 → {lst1 == lst2}")
# 预期输出：⑤ lst1 == lst2 → True

# 再对比一下：虽然内容相同，但它们是两个不同的列表对象
print(f"⑤ 补充：lst1 is lst2 → {lst1 is lst2}  ← 两个不同的列表对象")
# 预期输出：⑤ 补充：lst1 is lst2 → False

# ✅ 最终口诀：**值相等用 ==，和 None 打交道用 is，在不在用 in。**


