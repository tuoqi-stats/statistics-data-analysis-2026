# -*- coding: utf-8 -*-
"""
02_比较运算符.py —— 本章第 2 个示例文件

本节学什么：
    1. 六种比较运算符：==  !=  >  <  >=  <=
    2. 比较运算的结果永远是 bool 类型（True / False 两个值）
    3. == 和 = 的天壤之别（等于 vs 赋值）—— 新手第一大坑
    4. 数字、字符串、列表分别是怎么比较大小的
    5. 链式比较：Python 特有的 0 < x < 10 写法
    6. 浮点数比较的精度陷阱，以及正确做法

运行方式（在 VSCode 终端里）：
    python 02_比较运算符.py

预计输出：
    每个小节若干行 True / False 或说明性文字，共 63 行左右，
    全程无报错、无等待输入。

阅读方法：
    每一行 print() 上方的注释写的就是"这一行会输出什么"。
    看到 False 别急着觉得"错了"——False 往往正是本节要讲的重点。
"""

# ============================================================
# ===== 一、六个比较运算符 =====
# ============================================================
# 比较运算就是"问问题"，Python 回答你 True（是）或 False（否）。
# 像不像在考试卷上打勾打叉？True 就是勾，False 就是叉。
#
#   运算符 | 读作   | 例子     | 结果
#   -------|--------|----------|-------
#    ==    | 等于   | 3 == 3   | True
#    !=    | 不等于 | 3 != 4   | True
#    >     | 大于   | 3 > 4    | False
#    <     | 小于   | 3 < 4    | True
#    >=    | 大于等于 | 4 >= 4 | True
#    <=    | 小于等于 | 4 <= 3 | False

print("===== 一、六个比较运算符 =====")

a, b = 10, 20     # 一行给两个变量赋值（这叫"多重赋值"，也可以写成 a, b = 10, 20）

print(a == b)     # 预期输出：False  （10 等于 20 吗？否）
print(a != b)     # 预期输出：True   （10 不等于 20 吗？是）
print(a > b)      # 预期输出：False  （10 大于 20 吗？否）
print(a < b)      # 预期输出：True   （10 小于 20 吗？是）
print(a >= b)     # 预期输出：False  （10 大于等于 20 吗？否）
print(a <= b)     # 预期输出：True   （10 小于等于 20 吗？是）

# 相等的情况
print(a == 10)    # 预期输出：True
print(a >= 10)    # 预期输出：True   （相等时 >= 也算成立）
print(a <= 10)    # 预期输出：True


# ============================================================
# ===== 二、比较的结果永远是 bool 类型 =====
# ============================================================
# 这一点非常重要：比较运算不是"打印一个结果"就完了，
# 它产生的是一个实实在在的值，类型是 bool，可以存进变量、传进函数。
# 后面学 if 语句时，if 后面跟的就是这个 bool 值。

print("\n===== 二、结果是 bool 类型 =====")

result = 3 < 5
print(result)               # 预期输出：True
print(type(result))         # 预期输出：<class 'bool'>

# 💡 bool 只有两个值：True 和 False（首字母必须大写！）
is_pass = 90 >= 60
print(is_pass)              # 预期输出：True   （90 分及格了）
print(type(90 >= 60))       # 预期输出：<class 'bool'>

# 💡 有趣知识：bool 其实是 int 的子类，True 等于 1，False 等于 0
print(True == 1)            # 预期输出：True
print(False == 0)           # 预期输出：True
print(True + True)          # 预期输出：2     （可以当数字做加法）
print(int(True), int(False))  # 预期输出：1 0  （转成整数）

# ⚠️ 别把 "True"（字符串）和 True（布尔值）搞混
print(True == "True")       # 预期输出：False  （一个是布尔，一个是字符串）


# ============================================================
# ===== 三、⚠️ 大陷阱：= 和 == 不是一回事 =====
# ============================================================
# 这是零基础学 Python 最容易犯、也最难自己发现的错误，请重点看：
#
#     =   是「赋值」：把右边的值装进左边的变量里，是"动作"
#     ==  是「比较」：问"左右两边相等吗"，得到 True / False
#
# ⚠️ 很多语言（如 C/Java）里 if (x = 1) 能编译通过并造成 bug，
#    而 Python 会直接报错，算是帮你挡了一刀。但 x == 1 写成 x = 1
#    在语句级别不会报错，只是"悄悄做了别的事"，更难查。

print("\n===== 三、= 与 == 的区别 =====")

number = 5            # 这是赋值：把 5 存到 number 里（没有输出）
print(number)         # 预期输出：5
print(number == 5)    # 预期输出：True  （这是比较，问"number 是 5 吗"）
print(number == 6)    # 预期输出：False

# 💡 阅读代码时的小技巧：
#    看到 "=" 就在心里读「装进」，看到 "==" 就在心里读「等于吗」。
#    number = 5    → "把 5 装进 number"
#    number == 5   → "number 等于 5 吗"

# ⚠️ 另外注意：Python 里没有 <> 这种"不等于"写法（那是老语言的习惯）
# python 2 时代 <> 就已被弃用，现在写 <> 会直接 SyntaxError。


# ============================================================
# ===== 四、数字和字符串的比较 =====
# ============================================================
# 不同类型的比较规则不一样，核心记住一条：
# ⚠️ 数字和字符串之间用 > < 比较会直接报 TypeError，必须先转换类型！
#    （== 和 != 不会报错，直接返回 False）

print("\n===== 四、数字与字符串比较 =====")

# 数字比大小：就是数学上的比法
print(3 < 5)              # 预期输出：True
print(3.14 < 3.15)        # 预期输出：True
print(10 == 10.0)         # 预期输出：True   （10 和 10.0 数值相等，就是相等）

# 字符串比大小：按"字符编码"逐位比较（查字典的先后顺序）
# 'a' 的编码是 97，'b' 是 98，所以 'a' < 'b'；小写字母编码都大于大写字母
print("apple" == "apple")  # 预期输出：True
print("apple" == "Apple")  # 预期输出：False  （大小写不同就是不同！）
print("apple" < "banana")  # 预期输出：True   （a 开头比 b 开头小）
print("Z" < "a")           # 预期输出：True   （大写 Z(90) < 小写 a(97)）
print("abc" < "abd")       # 预期输出：True   （前两个字母相同，比第三个）
print("ab" < "abc")        # 预期输出：True   （短的是长的前缀，短的更小）

# ⚠️ 陷阱：字符串比大小不是按"长度"，也不是按"读音"
print("9" > "100")         # 预期输出：True   （按字符比，'9'>'1'）

# ⚠️⚠️ 大陷阱：字符串和数字比较，== 返回 False，但 > < 直接报错
print("18" == 18)          # 预期输出：False  （一个是文本，一个是数字）
print("18" != 18)          # 预期输出：True
# print("18" > 18)         # 这行会 TypeError: '>' not supported between 'str' and 'int'
# ✅ 正确做法：先转成同一类型再比
print(int("18") == 18)     # 预期输出：True   （把字符串转成数字再比）
print(str(18) == "18")     # 预期输出：True   （把数字转成字符串再比）


# ============================================================
# ===== 五、列表、元组也能比较 =====
# ============================================================
# 规则：逐个元素比，谁先在某一位置上分出大小就谁大，类似字符串。

print("\n===== 五、列表比较 =====")

print([1, 2, 3] == [1, 2, 3])   # 预期输出：True   （元素完全一样就相等）
print([1, 2] == [2, 1])         # 预期输出：False  （顺序不同就不等）
print([1, 2, 3] < [1, 2, 4])    # 预期输出：True   （前两个相同，3 < 4）
print([1, 2] < [1, 2, 0])       # 预期输出：True   （短列表是长列表前缀时，短的更小）

# ⚠️ 列表里元素类型不同时不能比大小（但能判相等）
# print([1, "a"] < [1, 2])      # TypeError，这里就不运行了

# 💡 嵌套列表也按同样规则递归比较
print([[1, 2], [3]] == [[1, 2], [3]])   # 预期输出：True


# ============================================================
# ===== 六、链式比较：Python 的优雅写法 =====
# ============================================================
# 数学里我们常写 0 < x < 10，Python 可以直接这样写！
# 它的含义是 (0 < x) and (x < 10)，但中间那个 x 只需要写一次。

print("\n===== 六、链式比较 =====")

x = 5
print(0 < x < 10)      # 预期输出：True   （等价于 0<x and x<10）
print(0 < x < 3)       # 预期输出：False  （x=5 不满足 x<3）

score = 85
# 判断成绩是否在 60~100 之间（含端点）
print(60 <= score <= 100)   # 预期输出：True

x = 15
print(0 < x < 10)      # 预期输出：False
print(10 <= x <= 20)   # 预期输出：True

# ⚠️ 陷阱：链式比较不能想当然地用在"逻辑或"的场景
#    想表达 "x 小于 0 或 x 大于 10" 不能写 0 > x > 10，
#    而应该写 x < 0 or x > 10（or 在下一个文件里讲）
x = 15
print(x < 0 or x > 10)     # 预期输出：True    ← 这才是正确写法


# ============================================================
# ===== 七、⚠️ 浮点数比较的精度陷阱 =====
# ============================================================
# 上一节见过 0.1 + 0.2 == 0.3 是 False，比较运算里更要当心这个坑。

print("\n===== 七、浮点数比较陷阱 =====")

print(0.1 + 0.2)             # 预期输出：0.30000000000000004
print(0.1 + 0.2 == 0.3)      # 预期输出：False  ← 千万别用 == 直接比浮点数！

# ✅ 正确做法一：用 round() 四舍五入到需要的小数位再比
print(round(0.1 + 0.2, 2) == 0.3)    # 预期输出：True

# ✅ 正确做法二：判断"两者之差的绝对值"是否足够小（工程上最常用）
diff = abs((0.1 + 0.2) - 0.3)
print(diff < 1e-9)                    # 预期输出：True   （1e-9 就是 10 的 -9 次方）

# 💡 结论：比较浮点数时，用"差值足够小"代替"完全相等"。
#    这是所有编程语言的通用经验，不是 Python 特有的毛病。


# ---------- 小结 ----------
# 1. 六种比较运算符：== != > < >= <=，结果永远是 bool 类型（True/False）。
# 2. ⚠️ = 是赋值，== 是比较，心里默念"装进"和"等于吗"来区分。
# 3. True 就是 1，False 就是 0，所以 True + True == 2。
# 4. 字符串按字符编码逐位比大小，且区分大小写；"18" 和 18 不相等。
# 5. 数字与字符串用 > < 比较会 TypeError，必须先 int() 或 str() 转换。
# 6. 链式比较 0 < x < 10 是 Python 特色，等价于 0<x and x<10。
# 7. ⚠️ 不要用 == 比较浮点数，用 round() 或"差值小于 1e-9"来判断。
