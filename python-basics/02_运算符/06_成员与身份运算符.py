"""
06_成员与身份运算符.py —— 本章第 6 个示例文件

本节学什么：
    1. 成员运算符：in / not in —— 判断"某个东西在不在里面"
    2. 身份运算符：is / is not —— 判断"是不是同一个对象"
    3. ⭐ is 和 == 的根本区别（本节最核心）
    4. 小整数缓存：为什么 -5~256 的 is 判断结果"看起来能用"
    5. 字符串驻留：为什么有些字符串 is 是 True，有些是 False
    6. ⚠️ 什么时候该用 is，什么时候该用 ==（附判断口诀）

运行方式（在 VSCode 终端里）：
    python 06_成员与身份运算符.py

预计输出：
    若干行 True / False 与说明文字，共 74 行左右，
    全程无报错、无等待输入。

阅读方法：
    第 4、5 小节的输出**依赖 Python 版本的实现细节**，
    本文件已按 CPython 3.13 的实际情况写好注释并验证过；
    但请你记住：**这些结果不该被依赖，写代码只用 == 比内容**。
"""

# ============================================================
# ===== 一、in：判断"在不在里面" =====
# ============================================================
# 语法： 元素 in 容器
# 返回 True 表示"在里面"，False 表示"不在"。
# 能用在字符串、列表、元组、字典、集合上，是 Python 里最顺口的语法之一。

print("===== 一、in 成员运算 =====")

# 1) 字符串：判断子串（注意是"子串"，不是"某个字符"）
print("a" in "apple")           # 预期输出：True
print("pp" in "apple")          # 预期输出：True   （连续的片段也算）
print("z" in "apple")           # 预期输出：False
print("apple" in "pineapple")   # 预期输出：True   （被包含在里面）
print("" in "apple")            # 预期输出：True   （空字符串是任何字符串的子串）

# 2) 列表：判断元素是否在列表中（精确匹配，不是子串）
print(3 in [1, 2, 3, 4])        # 预期输出：True
print(5 in [1, 2, 3, 4])        # 预期输出：False
print("a" in ["a", "b"])        # 预期输出：True
print([1, 2] in [1, 2, 3])      # 预期输出：False  （列表里没有"列表元素"[1,2]）
print([1, 2] in [[1, 2], [3]])  # 预期输出：True   （这个列表的元素才是列表）

# 3) 元组
print(2 in (1, 2, 3))           # 预期输出：True

# 4) 字典：⚠️ 判断的是"键 key"，不是"值 value"
user = {"name": "小明", "age": 18}
print("name" in user)           # 预期输出：True   （name 是键）
print("小明" in user)           # 预期输出：False  （小明是值，不是键）
print(18 in user)               # 预期输出：False  （值不参与 in 判断）
# 💡 想判断值可以用 user.values()
print("小明" in user.values())  # 预期输出：True

# 5) 集合
print(3 in {1, 2, 3})           # 预期输出：True

# 6) range 也可以
print(5 in range(1, 10))        # 预期输出：True

# ⚠️ 陷阱：数字和字符串不会互相匹配
print(3 in [1, 2, 3])           # 预期输出：True
print("3" in [1, 2, 3])         # 预期输出：False  ← 字符串 "3" 不是数字 3
print("3" in "123")             # 预期输出：True   （注意左边必须是字符串）

# ⚠️ 特别注意：数字 in 字符串会直接报错，例如写 3 in "123" 会得到
#    TypeError: 'in <string>' requires string as left operand, not int
#    所以这里不实际运行它，你只要记住：判断"字符在不在字符串里"，
#    左边一定要写成字符串形式，比如 "3" in "123"。


# ============================================================
# ===== 二、not in：不在里面 =====
# ============================================================
# not in 就是 in 的反面，写起来比 not (x in y) 更自然。
# 相当于在句子里说"……不在……里面"。

print("\n===== 二、not in 成员运算 =====")

print(5 not in [1, 2, 3, 4])    # 预期输出：True   （5 确实不在）
print(3 not in [1, 2, 3, 4])    # 预期输出：False  （3 在里面）
print("z" not in "apple")       # 预期输出：True
print("admin" not in {"admin", "root"})   # 预期输出：False

# 💡 实用场景 1：黑名单过滤
banned = ["badword1", "badword2"]
comment = "这是一条正常评论"
print(comment not in banned)    # 预期输出：True   （没被禁）

# 💡 实用场景 2：判断闰年（能被 4 整除且不能被 100 整除，或者能被 400 整除）
year = 2024
is_leap = (year % 4 == 0 and year % 100 != 0) or (year % 400 == 0)
print(is_leap)                  # 预期输出：True   （2024 是闰年）

# 💡 实用场景 3：检查多个值里有没有目标——比写一串 or 干净多了
choice = "y"
print(choice in ("y", "yes", "Y", "YES"))    # 预期输出：True
# 对比之前讲过的错误写法：choice == "y" or "yes" or "Y" —— 这是错的


# ============================================================
# ===== 三、is：判断"是不是同一个对象" =====
# ============================================================
# ⭐ 这是本节最重要的概念，请慢慢看：
#
#   ==  比较的是「值」——两个东西"长得一样吗"
#   is  比较的是「身份」——两个名字"是不是贴在同一件东西上"
#
# 💡 生活类比：
#    双胞胎兄弟，长得一模一样 → == 判断 True（值相同）
#    但他们是两个人            → is 判断 False（不是同一个对象）
#
# 技术上：is 比较的是 id()（对象在内存中的唯一编号）。

print("\n===== 三、is 与 == 的区别 =====")

# 用列表来演示最清楚（列表是可变对象，不会走缓存）
list_a = [1, 2, 3]
list_b = [1, 2, 3]
list_c = list_a          # 让 c 和 a 贴同一个列表

print(list_a == list_b)  # 预期输出：True    （内容一样）
print(list_a is list_b)  # 预期输出：False   ← 其实是两个不同的列表对象！
print(list_a is list_c)  # 预期输出：True    （c 就是 a，同一个对象）

# 用 id() 看"身份证号"，更直观
print(id(list_a) == id(list_b))   # 预期输出：False  （编号不同 = 两个对象）
print(id(list_a) == id(list_c))   # 预期输出：True   （编号相同 = 同一个对象）

# ✅ 结论：判断内容相等用 ==，判断是不是同一个对象才用 is。
#    99% 的场合你该用的是 ==！

# —— is not 就是 is 的反面 ——
print(list_a is not list_b)       # 预期输出：True   （确实不是同一个对象）
print(list_a is not list_c)       # 预期输出：False


# ============================================================
# ===== 四、⚠️ 为什么 is 比数字"看起来能用"（两种机制） =====
# ============================================================
# 有**两种**机制会让"is 比数字"意外返回 True，这也是它最迷惑人的地方：
#
#   机制① 小整数缓存：CPython 把 -5 到 256 的整数提前创建好并缓存，
#         所以这个范围内的数字只要值相同，用的就是同一个对象。
#
#   机制② 常量合并：同一个代码块里的相同字面量，编译期会被合并成一个对象。
#         这甚至能"越过"缓存范围，让 a = 257 / b = 257 的 is 也返回 True。
#
# ⚠️ 结果就是：用 is 比数字常常"碰巧是对的"，
#    让人误以为"is 可以用来比数字"——大错特错！
#    本节最后会用"运行时才算出来的值"戳破这个假象。

print("\n===== 四、小整数缓存 (-5 ~ 256) =====")

# ⚠️ 先说明一个容易把人绕晕的事实：
#    下面这些 a = 数字、b = 数字 的写法，**即使数字超出 -5~256 缓存范围**，
#    同一个代码块里相同的字面量也会被 Python 在编译期合并成同一个常量对象，
#    所以 is 结果依然是 True。
#    （真正的区别要靠"运行时计算出来"的值才能看出来，本小节最后有演示。）
#    正因为它"看起来总是 True"，才更容易让人误以为 is 能用来比数字。

# 缓存范围内：同一个对象
a = 100
b = 100
print(a == b)            # 预期输出：True
print(a is b)            # 预期输出：True    （100 在缓存里，是同一个对象）

# 缓存边界值 -5 和 256 也在缓存里
a = -5
b = -5
print(a is b)            # 预期输出：True    （-5 刚好在缓存下界）

a = 256
b = 256
print(a is b)            # 预期输出：True    （256 刚好在缓存上界）

# 超出缓存范围的字面量：因为常量合并，居然也显示 True
a = 257
b = 257
print(a == b)            # 预期输出：True    （值相等）
print(a is b)            # 预期输出：True    ← 注意！这里不是 False，
                         #   因为同代码块的相同字面量被合并成了同一个常量对象

a = -6
b = -6
print(a is b)            # 预期输出：True    （同样是常量合并的结果）

# ⚠️ 关键演示：只有当值是在"运行时算出来"的，is 才会露出真面目
big1 = int("1000")       # 运行时新建的对象
big2 = int("1000")       # 又一个运行时新建的对象
print(big1 == big2)      # 预期输出：True    （值相等）
print(big1 is big2)      # 预期输出：False   ← 这才是 is 的真实行为：两个不同对象！

# 和字面量赋值的情况对比一下，更能看出 is 有多不可靠
lit1 = 1000              # 字面量（编译期常量）
lit2 = int("1000")       # 运行时新建
print(lit1 is lit2)      # 预期输出：False   （一个是常量，一个是新建对象）
print(lit1 == lit2)      # 预期输出：True    （值相等，这才是你要的）

# ⚠️⚠️ 看到这里你应该彻底明白了：
#    同样是比较 1000，写成 1000 字面量时 is 是 True，
#    用 int("1000") 算出来时 is 却是 False —— 结果完全不可预测！
#    ✅ 所以：比数字永远用 ==，绝不要用 is。


# ============================================================
# ===== 五、⚠️ 字符串驻留：哪些字符串 is 会 True =====
# ============================================================
# "字符串驻留（interning）"：Python 会把一些"看起来像标识符"的短字符串
# 存进一张表里重复使用，所以相同内容可能就是同一个对象。
#
# 典型规则（CPython 实现细节，不是语言规范）：
#   ✓ 只含字母/数字/下划线、且长度较短的字符串，通常会被驻留
#   ✗ 含空格、特殊符号的字符串通常不会被驻留
#   ✗ 用运算拼出来的字符串通常是新对象

print("\n===== 五、字符串驻留 =====")

# 情况 1：看起来像标识符的短字符串，会被驻留
s1 = "hello"
s2 = "hello"
print(s1 == s2)          # 预期输出：True
print(s1 is s2)          # 预期输出：True   （被驻留了，同一个对象）

# 情况 2：含空格（不是合法标识符），通常不驻留
s3 = "hello world"
s4 = "hello world"
print(s3 == s4)          # 预期输出：True
print(s3 is s4)          # 预期输出：True   （同一代码块内字面量仍会被合并）

# ⚠️ 关键点来了：用运算"拼"出来的字符串是新对象
s5 = "hello" + " world"
print(s5 == s3)          # 预期输出：True   （内容一样）
print(s5 is s3)          # 预期输出：False  ← 拼接产生的是新对象！

# 用 str() 转换出来的也是新对象
s6 = str("hello")
print(s6 is s1)          # 预期输出：True  （CPython 对 str(str) 会直接返回原对象）

# 从输入、文件、网络来的字符串几乎肯定不是同一个对象
s7 = "".join(["he", "llo"])
print(s7 == s1)          # 预期输出：True
print(s7 is s1)          # 预期输出：False  ← 用 join 拼出来的，是新对象
print(s7 is s5)          # 预期输出：False

# ✅ 结论：字符串的 is 结果**完全不可预测**，取决于怎么造出来的。
#    判断字符串是否相等，**永远用 ==**。

# 💡 那什么时候必须用 is？只有一个标准答案：和 None 比较时。
#    Python 官方推荐（PEP 8）写 x is None，而不是 x == None。
value = None
print(value is None)             # 预期输出：True
print(value is not None)         # 预期输出：False
print(value == None)             # 预期输出：True，但官方不推荐这种写法


# ============================================================
# ===== 六、⚠️ 什么时候用 is / 什么时候用 ==（背下这张表） =====
# ============================================================
#   场景                        | 该用   | 原因
#   ----------------------------|--------|--------------------------------
#   比较数字、字符串、列表内容  | ==     | 你要的是"值相等"
#   判断是不是 None             | is     | None 全局唯一，官方推荐
#   判断是不是 True / False     | is     | 布尔值也是单例（但 == 也行）
#   判断两个名字是否同一对象    | is     | 比如检测"是不是同一个列表"
#   判断是否在容器里            | in     | 这才是成员判断的正道
#
# ✅ 记忆口诀：**"值相等用 ==，和 None 打交道用 is，在不在用 in。"**

print("\n===== 六、实战选择 =====")

# 1) 判断 None —— 用 is
result = None
if result is None:
    print("结果还没算出来")            # 预期输出：这一行会打印

# 2) 判断空 —— 直接用真假值（最 Python 的写法）
items = []
if not items:
    print("列表是空的")                # 预期输出：这一行会打印

# 3) 判断内容相等 —— 用 ==
name = "小明"
if name == "小明":
    print("名字匹配")                  # 预期输出：这一行会打印

# 4) 判断元素在不在 —— 用 in
status = "active"
if status in ("active", "pending"):
    print("状态有效")                  # 预期输出：这一行会打印

# 5) 判断是不是同一个对象（少见但合理）
a = [1, 2, 3]
b = a
if a is b:
    print("a 和 b 是同一个列表")       # 预期输出：这一行会打印
# 💡 这种写法在"函数收到参数想判断是不是外部传进来的同一个对象"时有用

# ⚠️ 反例集合（这些都是新手常犯的错，别这么写）：
# if age is 18:          ← 错！数字用 ==
# if name is "小明":     ← 错！字符串用 ==
# if x == None:          ← 能用但不地道，写 x is None
# if not "admin" in users:  ← 能用，但写 "admin" not in users 更清楚


# ---------- 小结 ----------
# 1. in / not in 判断"在不在容器里"，支持字符串、列表、元组、字典、集合。
# 2. ⚠️ 字典的 in 判断的是「键」，不是「值」；想查值用 dict.values()。
# 3. ⭐ == 比"值"，is 比"身份"（是不是同一个对象，即 id 是否相同）。
# 4. 小整数有缓存（-5~256），相同字面量还会被常量合并，
#    所以 is 比数字常常"碰巧"返回 True —— 但这恰恰说明它不可靠，
#    因为一旦值改成运行时算出来的（如 int("1000")），is 立刻变成 False。
# 5. 字符串驻留取决于内容与构造方式，is 的结果同样不可预测。
# 6. ✅ 口诀：值相等用 ==，和 None 打交道用 is，在不在用 in。
# 7. 判断"空"最地道的写法是 if not 变量:，而不是 if 变量 == []。
