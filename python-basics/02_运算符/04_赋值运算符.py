# -*- coding: utf-8 -*-
"""
04_赋值运算符.py —— 本章第 4 个示例文件

本节学什么：
    1. 基础赋值 = 的本质（把名字贴到对象上）
    2. 七种复合赋值：+=  -=  *=  /=  //=  %=  **=
    3. 复合赋值的"语法糖"本质：a += b 就是 a = a + b
    4. 多重赋值 a, b = 1, 2 与交换变量的骚操作
    5. 可迭代对象解包赋值 a, b = [1, 2]
    6. ⚠️ 可变对象的 += 会"原地修改"（列表的陷阱，重点！）
    7. 海象运算符 := （Python 3.8+ 的赋值表达式，了解即可）

运行方式（在 VSCode 终端里）：
    python 04_赋值运算符.py

预计输出：
    若干行数字、字符串、列表，共 58 行左右，
    全程无报错、无等待输入。

阅读方法：
    第六小节「列表的 += 陷阱」请务必亲手改代码试一遍，
    这是面试和实际工作中都常见的坑。
"""

# ============================================================
# ===== 一、基础赋值 = 的本质 =====
# ============================================================
# 我们说 "变量" 时，其实说的是一根"名字标签"。
# a = 10 的含义是：在内存里造一个 10，然后把 a 这个标签贴上去。
#
# ⚠️ 所以下面这种写法会让两个名字指向同一个东西，而不是复制一份：
#     b = a      →  b 和 a 贴的是同一个对象
# 对数字、字符串这类"不可变"对象没关系（改动会新建对象），
# 但对列表这类"可变"对象就要特别小心（见第六节）。

print("===== 一、基础赋值 =====")

a = 10
print(a)              # 预期输出：10

# 反复赋值：a 这个标签会贴到新对象上（旧的 10 没人引用后会被回收）
a = 20
print(a)              # 预期输出：20

# 用 id() 查看对象的"内存地址编号"，可以判断两个名字是否指向同一对象
b = a
print(a == b)         # 预期输出：True   （值相等）
print(a is b)         # 预期输出：True   （而且就是同一个对象）

# 重新给 b 赋值，a 完全不受影响（因为整数不可变，这里是新建了对象）
b = 99
print(a, b)           # 预期输出：20 99
print(a == b)         # 预期输出：False


# ============================================================
# ===== 二、七种复合赋值运算符 =====
# ============================================================
# 复合赋值 = "运算 + 赋值" 的缩写，用来更新变量自己。
#
#   运算符 | 等价于       | 例子              | 结果
#   -------|--------------|-------------------|------
#    +=    | x = x + y    | x=5; x+=3         | 8
#    -=    | x = x - y    | x=5; x-=3         | 2
#    *=    | x = x * y    | x=5; x*=3         | 15
#    /=    | x = x / y    | x=5; x/=2         | 2.5  （⚠️ 结果变 float）
#    //=   | x = x // y   | x=5; x//=2        | 2
#    %=    | x = x % y    | x=5; x%=2         | 1
#    **=   | x = x ** y   | x=5; x**=2        | 25
#
# 💡 为什么要用它？少打一遍变量名，意思更清楚，还能少犯"改错变量"的错。

print("\n===== 二、七种复合赋值 =====")

# += 累加：最常用，比如计数器
x = 5
x += 3               # 等价于 x = x + 3
print(x)             # 预期输出：8

# -= 累减
x = 5
x -= 3               # 等价于 x = x - 3
print(x)             # 预期输出：2

# *= 累乘
x = 5
x *= 3               # 等价于 x = x * 3
print(x)             # 预期输出：15

# ⚠️ /= 的结果一定是 float，哪怕能整除（和普通除法 / 的规矩一致）
x = 5
x /= 2               # 等价于 x = x / 2
print(x)             # 预期输出：2.5

x = 10
x /= 2
print(x)             # 预期输出：5.0   ← 注意是 5.0，不是 5
print(type(x))       # 预期输出：<class 'float'>

# //= 整除赋值（结果保持整数）
x = 5
x //= 2              # 等价于 x = x // 2
print(x)             # 预期输出：2
print(type(x))       # 预期输出：<class 'int'>

# %= 取模赋值：常用于"循环计数"，比如每满 10 归零
x = 5
x %= 2               # 等价于 x = x % 2
print(x)             # 预期输出：1

# **= 幂赋值
x = 5
x **= 2              # 等价于 x = x ** 2
print(x)             # 预期输出：25

# 复合赋值也支持字符串（+= 拼接、*= 重复）
s = "Hello"
s += " Python"       # 等价于 s = s + " Python"
print(s)             # 预期输出：Hello Python

s = "ab"
s *= 3               # 等价于 s = s * 3
print(s)             # 预期输出：ababab


# ============================================================
# ===== 三、复合赋值的实际用途：累加、累乘 =====
# ============================================================
# 学循环之前，先用数学公式体会一下 += 的威力——循环里天天用它。

print("\n===== 三、累加与累乘 =====")

# 求 1 + 2 + 3 + 4 + 5
total = 0                # 累加器必须从 0 开始
for i in range(1, 6):
    total += i           # 每次把 i 加进去
print(total)             # 预期输出：15

# 求 1 * 2 * 3 * 4 * 5（也就是 5 的阶乘）
product = 1              # ⚠️ 累乘器必须从 1 开始，从 0 开始永远是 0！
for i in range(1, 6):
    product *= i
print(product)           # 预期输出：120

# 前面提到过：累乘器从 0 开始会毁掉一切，这里验证一下
wrong_product = 0
for i in range(1, 6):
    wrong_product *= i
print(wrong_product)     # 预期输出：0   ← 0 乘任何数都是 0


# ============================================================
# ===== 四、多重赋值：一行写多个 =====
# ============================================================
# Python 允许一行给多个变量赋值，等号右边的会先按顺序算好。

print("\n===== 四、多重赋值 =====")

# 一次赋三个不同值
name, age, city = "小明", 18, "北京"
print(name)              # 预期输出：小明
print(age)               # 预期输出：18
print(city)              # 预期输出：北京

# 一次给多个变量赋同一个值（⚠️ 可变对象时会有联动风险，见第六节）
m = n = p = 0
print(m, n, p)           # 预期输出：0 0 0

# ⚠️ 陷阱：数量对不上会报 ValueError
# a, b = 1, 2, 3         # ValueError: too many values to unpack
# a, b, c = 1, 2         # ValueError: not enough values to unpack


# ============================================================
# ===== 五、交换变量：Python 的优雅写法 =====
# ============================================================
# 其他语言交换两个变量要借助临时变量：
#     temp = a; a = b; b = temp
# Python 一行就能搞定，靠的就是"右边先算好再统一赋值"的机制。

print("\n===== 五、交换变量 =====")

a, b = 1, 2
a, b = b, a              # 右边先算成 (2, 1)，再分别赋值
print(a, b)              # 预期输出：2 1

# 传统写法（对比用，效果一样，但多了一行）
a, b = 1, 2
temp = a
a = b
b = temp
print(a, b)              # 预期输出：2 1

# 三个变量也能循环交换
x, y, z = 1, 2, 3
x, y, z = z, x, y
print(x, y, z)           # 预期输出：3 1 2


# ============================================================
# ===== 六、⭐ 星号解包与"列表的 += 陷阱" =====
# ============================================================
# 左边带 * 的变量会"兜住"剩余的所有元素，得到列表。

print("\n===== 六、星号解包与列表陷阱 =====")

# 星号收集剩余元素
first, *rest = [1, 2, 3, 4, 5]
print(first)             # 预期输出：1
print(rest)              # 预期输出：[2, 3, 4, 5]

*init, last = [1, 2, 3, 4, 5]
print(init)              # 预期输出：[1, 2, 3, 4]
print(last)              # 预期输出：5

head, *middle, tail = [1, 2, 3, 4, 5]
print(head, middle, tail)   # 预期输出：1 [2, 3, 4] 5

# ---------- ⚠️⚠️ 本文件最重要的陷阱 ----------
# 对「列表」用 += 是**原地修改**（等价于 list.extend()），
# 所以所有指向同一个列表的名字都会一起变！
# 而对数字/字符串用 += 是"新建对象"，其他名字不受影响。

nums1 = [1, 2]
nums2 = nums1            # ⚠️ 注意：这不是复制，两个名字指向同一个列表
nums1 += [3, 4]
print(nums1)             # 预期输出：[1, 2, 3, 4]
print(nums2)             # 预期输出：[1, 2, 3, 4]  ← 跟着变了！因为它是同一个列表

# 对比：用普通的 + （不加等号）会新建一个列表，不影响原来的
nums3 = [1, 2]
nums4 = nums3
nums3 = nums3 + [3, 4]   # 新建列表后把 nums3 指向新列表
print(nums3)             # 预期输出：[1, 2, 3, 4]
print(nums4)             # 预期输出：[1, 2]       ← 没有跟着变！

# 那怎么复制列表？用切片 [:] 或 list() 或 .copy()
nums5 = [1, 2]
nums6 = nums5[:]         # 切片会生成新列表
nums5 += [3, 4]
print(nums5)             # 预期输出：[1, 2, 3, 4]
print(nums6)             # 预期输出：[1, 2]       ← 完好无损

# ✅ 结论：列表的 += 相当于 extend，是原地改；要复制就先 .copy()/切片。
#    （相同的坑还会出现在 `m = n = []` 这种多重赋值上，见下面）
m = n = []               # ⚠️ m 和 n 是同一个列表
m += [1]
print(m, n)              # 预期输出：[1] [1]     ← 两个都变了
# ✅ 正确做法：分开写
m, n = [], []
m += [1]
print(m, n)              # 预期输出：[1] []


# ============================================================
# ===== 七、海象运算符 := （了解即可） =====
# ============================================================
# Python 3.8 引入的"赋值表达式"：在表达式内部完成赋值并返回这个值，
# 好处是少写一行、少算一次。名字来源于 := 长得像海象的两颗牙。
#
# 💡 这里只做认识，实际项目里 if 语句配合它很好用，但不要滥用。

print("\n===== 七、海象运算符 =====")

# 普通写法：先算长度存变量，再判断
text = "hello"
length = len(text)
if length > 3:
    print(f"长度是 {length}，够长")        # 预期输出：长度是 5，够长

# 海象写法：在条件里顺手赋值，length2 之后仍可用
text = "hi"
if (length2 := len(text)) > 3:
    print(f"长度是 {length2}，够长")       # 预期输出：（不打印，因为 2 不大于 3）
print(f"不过 length2 已经被赋值了：{length2}")   # 预期输出：不过 length2 已经被赋值了：2

# 常见场景：while 里反复读取
countdown = 3
while (countdown := countdown - 1) > 0:
    print(f"倒计时 {countdown}")           # 预期输出：倒计时 2 / 倒计时 1（各一行）

# ⚠️ 注意：海象运算符必须加括号！不加括号在多数场合会 SyntaxError
# if length3 := len(text) > 3:              # SyntaxError，别这么写


# ---------- 小结 ----------
# 1. 基础赋值 = 是"贴名字"，b = a 不会复制可变对象，只多一个名字。
# 2. 七种复合赋值：+= -= *= /= //= %= **=，本质是 x = x <op> y 的缩写。
# 3. ⚠️ /= 的结果一定是 float；累乘器要从 1 开始，从 0 开始永远是 0。
# 4. 多重赋值 a, b = 1, 2；交换变量直接写 a, b = b, a。
# 5. 星号解包 first, *rest = [...] 可以兜住剩余元素，得到列表。
# 6. ⚠️⚠️ 列表的 += 是原地修改！nums2 = nums1 后 nums1 += [...] 会连带改动 nums2；
#    要复制列表请用 nums1[:] / list(nums1) / nums1.copy()。
# 7. 海象运算符 := 能在表达式里赋值，必须带括号，了解即可。
