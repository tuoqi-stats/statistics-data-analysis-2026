# ===== 1. 什么是嵌套 if =====
# 💡 生活类比：进门要过两道关卡 —— 先刷门禁卡，进去以后再按指纹。
#    外层的条件先成立，才会去判断里面的条件；外层不成立，内层根本看不到。

has_card = True       # 有门禁卡吗
has_fingerprint = True  # 指纹匹配吗

if has_card:
    # 预期输出：门禁通过
    print("门禁通过")
    if has_fingerprint:
        # 预期输出：指纹通过，可以进入办公区
        print("指纹通过，可以进入办公区")
    else:
        print("指纹不对，请找前台")
else:
    print("没有门禁卡，禁止入内")

# ⚠️ 缩进层级要一层比一层深，内层必须比外层多缩进（推荐 4 个空格）。


# ===== 2. 嵌套 vs 用 and 合并 —— 怎么选？ =====
# 💡 如果内层只是简单条件，用 and 写更清爽；
#    如果内层还要走 else 分支，用嵌套更清晰。

# 写法一：and 合并（推荐用于简单场景）
x = 10
if x > 0 and x < 100:
    # 预期输出：10 在 0~100 之间（and 写法）
    print(x, "在 0~100 之间（and 写法）")

# 写法二：嵌套（内层有独立的 else 时更合适）
if x > 0:
    if x < 100:
        # 预期输出：10 在 0~100 之间（嵌套写法）
        print(x, "在 0~100 之间（嵌套写法）")
    else:
        print(x, "太大了")
else:
    print(x, "不是正数")


# ===== 3. 多分支实战：判断三角形类型 =====
# 规则：先判断"能不能构成三角形"（任意两边之和大于第三边），
#       再判断是不是等边 / 等腰 / 普通三角形。

def triangle_type(a, b, c):
    """根据三条边返回三角形类型；构成不了就返回提示文字。"""
    if a + b > c and a + c > b and b + c > a:
        # 能构成三角形，继续细分
        if a == b and b == c:
            return "等边三角形"      # 三边都相等
        elif a == b or a == c or b == c:
            return "等腰三角形"      # 有两边相等
        else:
            return "普通三角形"
    else:
        return "无法构成三角形"

# 预期输出：三角形类型：等边三角形
print("三角形类型：", triangle_type(5, 5, 5))
# 预期输出：三角形类型：等腰三角形
print("三角形类型：", triangle_type(5, 5, 8))
# 预期输出：三角形类型：普通三角形
print("三角形类型：", triangle_type(3, 4, 5))
# 预期输出：三角形类型：无法构成三角形
print("三角形类型：", triangle_type(1, 2, 10))


# ===== 4. 真值测试：哪些值算"假"？ =====
# Python 的"假值"一共就这些常用几种：
#   0、0.0、""（空字符串）、[]（空列表）、{}（空字典）、()（空元组）、None、False
# 其余的值基本都是"真"。这叫"真值测试"。

false_like = [0, 0.0, "", [], {}, (), None, False]
for value in false_like:
    if value:
        # 预期输出：这里永远不会打印（它们都是假值）
        print("真的：", repr(value))
    else:
        # 预期输出：假值： 0 / 假值： 0.0 / 假值： '' ... 共 8 行
        print("假值：", repr(value))

# ⚠️ 新手常见坑：用 if 判断数字时，0 会走进 else 分支。
num = 0
if num:
    print("有值")
else:
    # 预期输出：num 是 0，被判定为假值
    print("num 是 0，被判定为假值")

# ✅ 如果 0 是合法数据、只是不想进 if，就显式写比较：
if num is not None:
    # 预期输出：num 不是 None（这才是稳妥的写法）
    print("num 不是 None（这才是稳妥的写法）")


# ===== 5. 真值测试实战：判断列表是否为空 =====
cart = []          # 空购物车
cart2 = ["苹果", "牛奶"]

# 💡 Pythonic 写法：直接用 if 列表，空列表为假
if cart:
    print("购物车里有东西")
else:
    # 预期输出：购物车是空的，不能结算
    print("购物车是空的，不能结算")

if cart2:
    # 预期输出：购物车有 2 件商品
    print("购物车有", len(cart2), "件商品")
else:
    print("购物车是空的")


# ===== 6. 综合实战：判断闰年 =====
# 闰年规则：能被 4 整除但不能被 100 整除，或者能被 400 整除。

def is_leap_year(year):
    """判断是否为闰年，返回 True / False。"""
    if year % 400 == 0:
        return True
    elif year % 100 == 0:
        return False
    elif year % 4 == 0:
        return True
    else:
        return False

for y in [2000, 1900, 2024, 2023]:
    # 预期输出：2000 闰年： 是 / 1900 闰年： 否 / 2024 闰年： 是 / 2023 闰年： 否
    print(y, "闰年：", "是" if is_leap_year(y) else "否")


# ===== 7. 综合实战：根据分数给建议（嵌套 + 多分支） =====
def advice(score):
    """分数为 0~100 时给出等级和建议。"""
    if score < 0 or score > 100:
        # 先做合法性校验，避免后面判断混乱
        return "分数不合法"
    if score >= 90:
        if score == 100:
            return "满分！太厉害了 🎉"
        return "优秀，继续保持"
    elif score >= 60:
        return "及格，还可以更好"
    else:
        return "不及格，需要加油"

# 预期输出：105 -> 分数不合法
print(105, "->", advice(105))
# 预期输出：100 -> 满分！太厉害了 🎉
print(100, "->", advice(100))
# 预期输出：75 -> 及格，还可以更好
print(75, "->", advice(75))
# 预期输出：40 -> 不及格，需要加油
print(40, "->", advice(40))


# ---------- 小结 ----------
# 1. 嵌套 if：外层条件成立才轮到内层判断，缩进层级逐层加深。
# 2. 简单并列条件用 and / or 合并更清爽；内层有独立 else 时用嵌套。
# 3. 假值清单要记住：0、0.0、""、[]、{}、()、None、False。
# 4. 如果 0 是有效数据，别直接 if num，要写 if num is not None 之类的显式判断。
# 5. 复杂判断先做"合法性校验"，再进入业务分支，代码更不容易出错。
