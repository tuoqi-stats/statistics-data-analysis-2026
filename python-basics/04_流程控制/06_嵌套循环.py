# ===== 1. 什么是嵌套循环 =====
# 💡 生活类比：学校做广播体操 —— 先按"班级"排队（外层），
#    每个班级里再按"学号"点人（内层）。外层走一步，内层要全部走完。
# ⚠️ 核心规律：外循环每执行 1 次，内循环要完整执行一整轮。
#    所以内循环的总次数 = 外层次数 × 内层次数。

print("--- 嵌套循环基础演示 ---")
for i in range(1, 4):          # 外层：班级
    for j in range(1, 3):      # 内层：学号
        # 预期输出：班级1-学号1 / 班级1-学号2 / 班级2-学号1 / 班级2-学号2 / 班级3-学号1 / 班级3-学号2（共 6 行）
        print("班级" + str(i) + "-学号" + str(j))
# 💡 一共 3 × 2 = 6 行输出。


# ===== 2. 打印直角三角形（星星逐个增多） =====
# 💡 思路：外层控制"第几行"，内层控制"这一行打几个星星"。
#    用字符串乘法 "⭐" * n 最简单。

print("\n--- 直角三角形 ---")
for row in range(1, 6):        # 第 1 行到第 5 行
    stars = "⭐" * row          # 第 row 行打 row 个星星
    # 预期输出：⭐ / ⭐⭐ / ⭐⭐⭐ / ⭐⭐⭐⭐ / ⭐⭐⭐⭐⭐
    print(stars)


# ===== 3. 打印倒三角形（星星逐个减少） =====
# 💡 关键：range 倒着走，用 range(起点, 终点, -1)。

print("\n--- 倒三角形 ---")
for row in range(5, 0, -1):    # 5, 4, 3, 2, 1
    # 预期输出：⭐⭐⭐⭐⭐ / ⭐⭐⭐⭐ / ⭐⭐⭐ / ⭐⭐ / ⭐
    print("⭐" * row)


# ===== 4. 打印金字塔（空格 + 星星） =====
# 💡 两种字符配合：前面补空格把星星推到中间。
#    第 row 行有 (总行数 - row) 个空格，有 (2 * row - 1) 个星星。

print("\n--- 金字塔 ---")
total_rows = 5
for row in range(1, total_rows + 1):
    spaces = "  " * (total_rows - row)      # 用两个空格当一格，看起来更宽
    stars = "⭐" * (2 * row - 1)             # 奇数增长：1, 3, 5, 7, 9
    print(spaces + stars)


# ===== 5. ⭐ 九九乘法表（嵌套循环最经典的例子） =====
# 💡 思路：两层循环，外层是被乘数 i（1~9），内层是乘数 j（1~i）。
#    内层只到 i，才能打印出"三角形"形状，也就是完整的 45 条。

print("\n--- 九九乘法表 ---")
for i in range(1, 10):              # 外层：第几行
    line_parts = []                 # 收集这一行的每一小段
    for j in range(1, i + 1):       # 内层：1 到 i，共 i 个算式
        line_parts.append(f"{j}x{i}={i * j}")   # f-string 更方便拼字符串
    # 用两个空格连接成一行打印
    # 预期输出（部分）：1x1=1 / 1x2=2  2x2=4 / ... 最后一行有 9 个算式，共 9 行
    print("  ".join(line_parts))

# ⚠️ 常见错误：内层写成 range(1, 10) 会打印完整 81 条，形状变成正方形。
#    想要三角形就写成 range(1, i + 1)。

print("\n--- 验证：完整乘法表一共多少条 ---")
count = 0
for i in range(1, 10):
    for j in range(1, 10):
        count += 1
# 预期输出：9x9 正方形表格共 81 条
print("9x9 正方形表格共", count, "条")
count2 = 0
for i in range(1, 10):
    for j in range(1, i + 1):
        count2 += 1
# 预期输出：三角形乘法表共 45 条（1+2+...+9）
print("三角形乘法表共", count2, "条（1+2+...+9）")


# ===== 6. 遍历二维列表（列表里面套列表） =====
# 💡 二维列表就像表格：外层是"行"，内层是"列"。

matrix = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9],
]

# 逐行打印
print("\n--- 二维列表逐行打印 ---")
for row in matrix:
    # 预期输出：[1, 2, 3] / [4, 5, 6] / [7, 8, 9]
    print(row)

# 逐元素打印（真正的双层遍历）
print("\n--- 二维列表逐元素打印 ---")
for row in matrix:             # 外层拿行
    for value in row:          # 内层拿行里的每个元素
        # 预期输出：1 2 3 / 4 5 6 / 7 8 9（每行三个数字）
        print(value, end=" ")
    print()                    # 每行结束换行（print() 不传参数就是空行）

# 计算所有元素的和
matrix_sum = 0
for row in matrix:
    for value in row:
        matrix_sum += value
# 预期输出：二维列表元素之和： 45
print("二维列表元素之和：", matrix_sum)


# ===== 7. 嵌套循环实战：找出 1~20 内的所有质数 =====
# 💡 思路：外层遍历每个数，内层判断它能不能被更小的数整除。
#    这里用了一个小技巧：内层只需要试到平方根，能大幅减少计算量。

print("\n--- 1~20 内的质数 ---")
primes = []
for num in range(2, 21):               # 外层：待判断的数
    is_prime = True
    divisor = 2
    while divisor * divisor <= num:    # 内层：只试到平方根
        if num % divisor == 0:
            is_prime = False
            break                      # 找到因子就不用再试了
        divisor += 1
    if is_prime:
        primes.append(num)

# 预期输出：1~20 内的质数： [2, 3, 5, 7, 11, 13, 17, 19]
print("1~20 内的质数：", primes)


# ===== 8. 嵌套循环性能提醒 =====
# ⚠️ 内层次数会被外层次数"放大"：10 × 10 = 100，1000 × 1000 = 100 万。
#    所以嵌套层数越深越慢，能用一层就别用两层。
#    下面这个例子只跑了 100 次，很安全；真实项目中要留意循环规模。

counter = 0
for i in range(10):
    for j in range(10):
        counter += 1
# 预期输出：10 x 10 循环共执行了 100 次
print("10 x 10 循环共执行了", counter, "次")


# ===== 9. 用 break 只能跳出"最内层"循环 =====
# ⚠️ 这是新手最容易懵的点：内层的 break 只结束内层，外层照样继续！

print("\n--- break 只跳出内层演示 ---")
for outer in range(1, 4):
    for inner in range(1, 4):
        if inner == 2:
            # 预期输出：内层跳出（出现 3 次，每次外层迭代各一次）
            print("内层跳出")
            break                  # 只结束 inner 这一层
        # 预期输出：外层 1 / 外层 2 / 外层 3（每个只打印一次，因为内层在 inner=2 就跳出了）
        print("外层", outer)

# 💡 想跳出所有外层怎么办？常见做法是用一个"标志变量"控制：
print("\n--- 跳出所有层：标志变量法 ---")
found = False
for outer in range(1, 4):
    for inner in range(1, 4):
        if outer * inner == 4:
            # 预期输出：找到了：outer=1, inner=4 -> 不，这里是 2 乘 2
            print("找到了：outer =", outer, ", inner =", inner)
            found = True
            break                  # 先跳内层
    if found:
        break                      # 再跳外层，实现"一次性全跳出"


# ---------- 小结 ----------
# 1. 嵌套循环：外循环每走 1 步，内循环完整走一轮；总次数 = 外层 × 内层。
# 2. 打印图形的套路：外层控制"行"，内层控制"这一行打印几个字符"。
# 3. 九九乘法表的关键是内层写成 range(1, i + 1)，才能得到三角形。
# 4. 二维列表用双层 for 遍历；print(value, end=" ") 可以不换行输出。
# 5. ⚠️ break 只能跳出最内层，要全跳出得配一个标志变量。
# 6. ⚠️ 嵌套层数越多性能越差，注意循环规模。
