# -*- coding: utf-8 -*-
"""
============================================================
本文件学什么：if / elif / else 条件判断的基本结构
------------------------------------------------------------
运行方式：
    在 VSCode 中打开本文件，按 Ctrl+F5 运行；
    或在终端执行：python 01_if条件判断.py

预计输出：
    一段一段的判定结果文字，例如 "成年了"、"成绩等级：B" 等，
    最后有一行 "小结" 内容。整个脚本瞬间结束，不需要输入任何内容。
============================================================
"""

# ===== 1. 为什么需要条件判断 =====
# 💡 生活类比：出门前看天气 —— 如果下雨就带伞，否则就不带。
#    "如果……就……，否则……" 就是程序里的 if / else。
#    程序默认从第一行执行到最后一行，有了条件判断，就能"分岔走路"。

# if 的语法格式（注意冒号 和 缩进）：
#     if 条件:
#         条件为真时执行的代码
# 条件为真(True)才执行缩进的代码；为假(False)就跳过。

weather = "下雨"

if weather == "下雨":
    # 预期输出：带伞 ☂️
    print("带伞 ☂️")

# ⚠️ 注意：Python 靠"缩进"划分代码块，不是靠大括号 {}。
#    下面这行没有缩进，所以它在 if 之外，无论条件真假都会执行。
# 预期输出：出门
print("出门")


# ===== 2. if ... else：两种情况二选一 =====
# else 表示"其他所有情况"，它不需要写条件，也不能单独使用。

age = 20

if age >= 18:
    # 预期输出：成年了，可以独立签合同
    print("成年了，可以独立签合同")
else:
    # 预期输出：未成年，需要监护人
    print("未成年，需要监护人")


# ===== 3. 条件表达式的真假（真值测试） =====
# 数字 0、空字符串 ""、空列表 []、None 都算"假"，其余大多算"真"。
# 💡 类比：空盒子算"没有东西"，装了东西的盒子算"有东西"。

score = 0

if score:
    # 0 是假值，所以这行不会执行
    print("这句话不会打印出来")
else:
    # 预期输出：score 是 0，被当成假值
    print("score 是 0，被当成假值")


# ===== 4. elif：多分支，从上往下逐个判断 =====
# elif 是 "else if" 的缩写，可以有任意多个。
# ⚠️ 关键规则：只要有一个分支成立，后面的分支就全部跳过，不再判断。

student_score = 82

if student_score >= 90:
    grade = "A"
elif student_score >= 80:
    grade = "B"   # 82 满足 >= 80，命中这里
elif student_score >= 60:
    grade = "C"
else:
    grade = "D"

# 预期输出：成绩等级：B
print("成绩等级：", grade)

# 💡 顺序很重要！如果把 >= 60 写在最前面，
#    那么 82 会先命中 >= 60，得到错误的结果 C。
#    所以多分支判断要从"最严格"排到"最宽松"。


# ===== 5. 用 in 做成员判断 =====
# 💡 "in" 相当于问：这个东西在不在这个容器里？

role = "admin"
allowed = ["admin", "manager"]

if role in allowed:
    # 预期输出：有管理权限
    print("有管理权限")
else:
    print("没有管理权限")


# ===== 6. 用 and / or / not 组合条件 =====
# and：两边都成立才成立；or：任意一边成立就成立；not：取反。

height = 175
weight = 70

if height > 170 and weight > 70:
    # weight 是 70，不满足 > 70，所以条件为假
    print("这句话不会打印")
elif height > 170 or weight > 70:
    # 预期输出：身高条件满足，通过
    print("身高条件满足，通过")
else:
    print("都不满足")

is_weekend = False
if not is_weekend:
    # 预期输出：今天是工作日，去上班
    print("今天是工作日，去上班")


# ===== 7. 条件表达式（一行版 if-else，也叫三元表达式） =====
# 语法：值1 if 条件 else 值2
# 💡 适合简单的二选一，复杂逻辑还是用多行 if 更易读。

n = 7
parity = "偶数" if n % 2 == 0 else "奇数"
# 预期输出：7 是 奇数
print(n, "是", parity)


# ===== 8. 综合小例子：判断能否看电影 =====
# 规则：年龄 >= 12 或者 有家长陪同，就可以看。

person_age = 10
has_parent = True

if person_age >= 12:
    can_watch = True
elif has_parent:
    can_watch = True
else:
    can_watch = False

# 预期输出：10 岁能否观影：True
print(person_age, "岁能否观影：", can_watch)


# ---------- 小结 ----------
# 1. if 条件: 后面必须有冒号，代码块靠缩进（建议 4 个空格）划分。
# 2. else 是兜底分支，可以不写；elif 可以有多个，按顺序匹配，命中即停。
# 3. 多分支判断要从严格到宽松排列，否则会被宽条件提前截胡。
# 4. 0、""、[]、None 等是"假值"，if 判断时会走 else 分支。
# 5. 简单二选一可以用"值1 if 条件 else 值2"写成一行。
print("\n[01] if 条件判断 学习完成 ✅")
