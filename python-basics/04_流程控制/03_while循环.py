# -*- coding: utf-8 -*-
"""
============================================================
本文件学什么：while 循环的基本用法、计数器、累加器
------------------------------------------------------------
运行方式：
    在 VSCode 中打开本文件，按 Ctrl+F5 运行；
    或在终端执行：python 03_while循环.py

预计输出：
    从 1 数到 5 的过程、1~100 的累加结果 5050、猜数字模拟过程等。
    ⚠️ 本文件所有循环都有明确终止条件，几毫秒内跑完，不会卡死。
============================================================
"""

# ===== 1. while 的基本结构 =====
# 💡 生活类比：跑步机 —— 只要没跑够 10 分钟就继续跑，跑够了就停。
# 语法：
#     while 条件:
#         循环体（条件为真就重复执行）
# ⚠️ 循环体里必须有让条件"最终变假"的语句，否则就是死循环！

count = 1              # 计数器：从 1 开始

while count <= 5:      # 只要 count 不大于 5 就继续
    # 预期输出：第 1 次循环 / 第 2 次循环 ... 第 5 次循环（共 5 行）
    print("第", count, "次循环")
    count = count + 1  # ⚠️ 关键：让计数器递增，否则永远停在 1

# 循环结束后 count 已经变成 6
# 预期输出：循环结束，count = 6
print("循环结束，count =", count)


# ===== 2. 计数器：统计次数 =====
# 💡 计数器就是"数一数发生了几次"，初始值通常是 0，每发生一次加 1。

n = 1
even_count = 0        # 计数器：统计偶数个数

while n <= 10:
    if n % 2 == 0:    # 能被 2 整除就是偶数
        even_count += 1
    n += 1            # 等价于 n = n + 1

# 预期输出：1~10 中偶数个数： 5
print("1~10 中偶数个数：", even_count)


# ===== 3. 累加器：把值一点点攒起来 =====
# 💡 累加器就像存钱罐，初始值是 0，每次往里面加一点。
# ⚠️ 一定要把累加器初始化在循环外面，写循环里面会被反复清零！

i = 1
total = 0             # 累加器：初始值必须是 0

while i <= 100:
    total += i        # 把 i 加进总和
    i += 1

# 预期输出：1+2+...+100 = 5050
print("1 + 2 + ... + 100 =", total)

# 💡 有个数学公式能直接算：n*(n+1)/2，结果应该一致
# 预期输出：用公式验证： 5050
print("用公式验证：", 100 * 101 // 2)


# ===== 4. 累乘器：求阶乘 =====
# 💡 累乘器初始值必须是 1（不能是 0，否则乘出来永远是 0）。

k = 1
factorial = 1         # 累乘器：初始值 1

while k <= 5:
    factorial *= k    # 等价于 factorial = factorial * k
    k += 1

# 预期输出：5! = 120
print("5! =", factorial)


# ===== 5. 计数器的三种写法对比 =====
# 写法一：最啰嗦，但最直白
a = 0
while a < 3:
    a = a + 1
# 预期输出：写法一结果 a = 3
print("写法一结果 a =", a)

# 写法二：用 += 复合赋值，推荐
b = 0
while b < 3:
    b += 1
# 预期输出：写法二结果 b = 3
print("写法二结果 b =", b)

# 写法三：步长不是 1，比如每次 +2
c = 0
while c < 10:
    c += 2
# 预期输出：写法三结果 c = 10
print("写法三结果 c =", c)


# ===== 6. 倒数计时（条件递减） =====
# 💡 循环不一定往上加，也可以往下减。

countdown = 5
result = []           # 用列表把每次的值收集起来，方便一次性打印

while countdown > 0:
    result.append(countdown)
    countdown -= 1    # 每次减 1，最终会减到 0，循环结束

# 预期输出：倒数计时： [5, 4, 3, 2, 1]
print("倒数计时：", result)


# ===== 7. 模拟猜数字（不需要用户输入） =====
# 💡 真实场景要用 input() 让用户猜，这里我们用"预设答案列表"来模拟，
#    这样脚本可以自动跑完，不用等输入。
# ⚠️ 必须给尝试次数设上限，否则猜不中就死循环了。

secret = 42
guesses = [10, 30, 50, 42]   # 模拟用户依次猜的数字
idx = 0
max_tries = 10               # ⚠️ 安全阀：最多猜 10 次
tries = 0

while idx < len(guesses) and tries < max_tries:
    guess = guesses[idx]
    tries += 1
    if guess < secret:
        # 预期输出：猜 10，太小了 / 猜 30，太小了
        print(f"猜 {guess}，太小了")
    elif guess > secret:
        # 预期输出：猜 50，太大了
        print(f"猜 {guess}，太大了")
    else:
        # 预期输出：猜 42，猜中了！共用 4 次
        print(f"猜 {guess}，猜中了！共用 {tries} 次")
        break                # 猜中就跳出循环
    idx += 1


# ===== 8. 用 while 处理"不确定次数"的任务：整数位数 =====
# 💡 while 最擅长"不知道要循环几次"的场景，比如数字除法直到变 0。

number = 20240
temp = number
digits = 0

while temp > 0:
    temp //= 10    # 整除 10，相当于去掉最后一位
    digits += 1

# 预期输出：20240 有 5 位数字
print(number, "有", digits, "位数字")


# ---------- 小结 ----------
# 1. while 条件: 循环体 —— 条件为真就反复执行，为假才退出。
# 2. ⚠️ 循环体里必须修改条件相关的变量，否则就是死循环。
# 3. 计数器：初始 0，命中一次 +1，用来统计次数。
# 4. 累加器：初始 0；累乘器：初始 1（写 0 会全归零）。
# 5. while 适合"次数不确定"的任务（如猜数字、拆数字），for 适合"次数已知"的任务。
print("\n[03] while 循环 学习完成 ✅")
