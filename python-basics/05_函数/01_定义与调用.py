"""
================ 01 函数的定义与调用 ================

【本文件学什么】
  1. 用 def 定义一个函数
  2. 调用函数（函数不会自己运行，必须"叫"它）
  3. docstring（文档字符串）：给函数写说明书
  4. 用 help() 查看函数说明
  5. 返回值 return 的初体验

【怎么运行】
  在 VSCode 里打开本文件，直接点右上角 ▶ 运行；
  或在终端执行：
      python 01_定义与调用.py

【预计输出】
  会依次看到 6 个分节的结果，每行 print 的结果都在代码上方用注释写明了。
  文件末尾会打印"小结"。
"""


# ===== 1. 最简单的函数：定义 + 调用 =====

# 定义函数用 def 关键字。
# 类比：def 就像"买回来一台料理机并起个名字"，此时机器还没转。
# 函数体的代码必须缩进（通常 4 个空格），缩进代表"这些代码属于这个函数"。
def say_hello():
    print("  你好，我是 say_hello 函数")

# 💡 注意：上面只完成了"定义"，程序运行到这里并不会打印任何东西。
# 只有下面这行"调用"发生，函数体才会真正执行。
# 调用方式：函数名 + 一对括号 ()
say_hello()

# 预期输出：你好，我是 say_hello 函数
print("--- 1. 最简单的函数结束 ---")


# ===== 2. 带参数的函数：把数据"喂"进去 =====

# 括号里的 name 叫"参数"（形参），是函数内部使用的一个变量。
# 类比：参数就是放进料理机的食材，每次调用可以放不同的食材。
def greet(name):
    print(f"  你好，{name}！欢迎学习 Python 函数")

# 调用时传入的 "小明" 叫"实参"，会赋值给形参 name
greet("小明")

# 预期输出：你好，小明！欢迎学习 Python 函数
greet("小红")

# 预期输出：你好，小红！欢迎学习 Python 函数
print("--- 2. 带参数的函数结束 ---")


# ===== 3. docstring（文档字符串）：给函数写说明书 =====

def add(a, b):
    """
    计算两个数的和。

    参数:
        a (int | float): 第一个加数
        b (int | float): 第二个加数

    返回:
        int | float: a 与 b 的和

    示例:
        >>> add(1, 2)
        3
    """
    # 紧跟在 def 下面的三引号字符串，就是 docstring（文档字符串）。
    # 它不是普通注释，Python 会把它保存在函数的 __doc__ 属性里，可以被工具读取。
    result = a + b
    return result

# 把两个数相加的结果算出来并打印
print(f"  add(3, 5) = {add(3, 5)}")

# 预期输出：add(3, 5) = 8
print("--- 3. docstring 结束 ---")


# ===== 4. 用 help() 查看文档 =====

# help() 会打印出函数的 docstring，相当于"查看说明书"。
# 注意：help() 的输出较长，这里只打印分隔线方便阅读。
print("  下面用 help(add) 查看 add 函数的说明书 ↓")
help(add)
print("  ↑ 上面就是 add 函数的说明书内容")
print("--- 4. help() 结束 ---")


# ===== 5. 直接读取 __doc__ 属性 =====

# 函数对象的 __doc__ 属性保存着 docstring 文本。
# .strip() 用来去掉首尾多余的空白和换行，方便打印。
print("  add.__doc__ 的第一行内容如下：")
print(f"    {add.__doc__.strip().splitlines()[0]}")

# 预期输出：计算两个数的和。
print("--- 5. __doc__ 属性结束 ---")


# ===== 6. return 初体验：把结果"交出来" =====

def square(x):
    """返回 x 的平方。"""
    # return 的两个作用：
    #   ① 结束当前函数的执行
    #   ② 把后面的值交还给调用者
    return x * x

# 调用 square 后得到返回值 5*5=25，再交给 print 打印
print(f"  square(5) = {square(5)}")

# 预期输出：square(5) = 25

# 返回值可以直接参与运算
total = square(3) + square(4)
print(f"  square(3) + square(4) = 3² + 4² = {total}")

# 预期输出：square(3) + square(4) = 3² + 4² = 25
print("--- 6. return 初体验结束 ---")


# ---------- 小结 ----------
# 1. def 函数名():        → 定义函数，只是"登记"，不会执行
# 2. 函数名()             → 调用函数，函数体才会真正运行
# 3. 参数写在括号里       → 让函数可以接收不同的数据，实现复用
# 4. docstring            → 紧跟 def 的三引号字符串，是函数的说明书
# 5. help(函数名)         → 查看说明；函数名.__doc__ 也能拿到说明文字
# 6. return               → 结束函数并把结果交还给调用者
# 💡 记住一句话：定义 ≠ 执行，加括号才执行。
