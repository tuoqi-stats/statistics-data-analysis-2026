"""
03_字符串表达式.py —— 字符串拼接、重复、f-string 格式化、format()

【本文件学什么】
  1. 字符串的 + 拼接、* 重复
  2. f-string：最推荐的格式化方式
  3. str.format()：老牌写法，读旧代码要看懂
  4. % 格式化：更老的写法，认识即可
  5. 常见格式控制：小数位数、百分比、千分位、对齐、宽度

【运行方式】
  在 VSCode 终端里执行：  python 03_字符串表达式.py

【预计输出】
  各种字符串拼接与格式化后的结果，包含对齐排版效果，
  1 秒内跑完，无需任何输入。
"""

# ===== 1. 字符串拼接：+ =====
# + 把两个字符串"粘"在一起，返回一个新字符串。
# ⚠️ 两边必须都是字符串，字符串 + 数字会直接报错。

print("---------- 1. 字符串拼接 + ----------")

first = "张"
last = "三"

# 预期输出：姓名：张三
print("姓名：" + first + last)

# 字面量直接相加
# 预期输出：Hello World
print("Hello" + " " + "World")

# 想要中间加符号，就把符号当成字符串一起拼
# 预期输出：2026-09-24
print("2026" + "-" + "09" + "-" + "24")

# 空字符串是拼接的"零"，加上它结果不变
# 预期输出：abc
print("a" + "" + "b" + "c")

# ⚠️ 字符串 + 数字会报 TypeError，所以必须先把数字转成字符串
age = 18
# 预期输出：年龄：18
print("年龄：" + str(age))

# 下面这行会报错，注释掉演示：
# print("年龄：" + age)   # TypeError: can only concatenate str (not "int") to str


# ===== 2. 字符串重复：* =====
# 字符串 * 整数 = 把字符串重复若干次。
# 💡 只能乘以整数，乘以浮点数会报错。

print("---------- 2. 字符串重复 * ----------")

# 预期输出：======
print("=" * 6)

# 预期输出：哈哈哈哈哈
print("哈" * 5)

# 乘 0 或负数得到空字符串
# 预期输出：长度 = 0
print("长度 =", len("abc" * 0))

# 预期输出：长度 = 0
print("长度 =", len("abc" * -1))

# 实用场景：画分隔线
# 预期输出：*****
print("*" * 5)

# 实用场景：简单缩进
# 预期输出：    缩进了4格
print(" " * 4 + "缩进了4格")

# 注意：列表也能用 * 重复，规则类似
# 预期输出：[0, 0, 0]
print([0] * 3)


# ===== 3. f-string：最推荐的格式化方式 =====
# 语法：在引号前加 f，字符串里用 {变量名} 占位。
# 优点：括号里可以直接写表达式，可读性最好，Python 3.6+ 都支持。

print("---------- 3. f-string（首选） ----------")

name = "小明"
score = 92.5
count = 3

# 直接把变量塞进去
# 预期输出：小明 的得分是 92.5
print(f"{name} 的得分是 {score}")

# 花括号里可以写任意表达式
# 预期输出：3 年后是 21 岁
age = 18
print(f"{3} 年后是 {age + 3} 岁")

# 可以直接调用函数
# 预期输出：名字长度：2
print(f"名字长度：{len(name)}")

# 可以在花括号里写条件表达式
# 预期输出：评价：优秀
print(f"评价：{'优秀' if score >= 90 else '良好'}")

# 花括号里也能做运算和格式控制（见下一节）
# 预期输出：总分：100
print(f"总分：{score + 7.5:.0f}")


# ===== 4. 格式控制：小数、百分比、千分位 =====
print("---------- 4. 格式控制 ----------")

pi = 3.141592653589793

# :.2f 表示保留 2 位小数（会四舍五入）
# 预期输出：PI ≈ 3.14
print(f"PI ≈ {pi:.2f}")

# :.0f 表示不留小数
# 预期输出：PI ≈ 3
print(f"PI ≈ {pi:.0f}")

# :.4f 保留 4 位
# 预期输出：PI ≈ 3.1416
print(f"PI ≈ {pi:.4f}")

# :.1% 表示先乘 100 再加百分号，保留 1 位小数
rate = 0.8567
# 预期输出：通过率：85.7%
print(f"通过率：{rate:.1%}")

# :, 表示千分位分隔符
money = 1234567.891
# 预期输出：金额：￥1,234,567.89
print(f"金额：￥{money:,.2f}")

# :d 表示整数，:05d 表示不足 5 位左边补 0
idx = 42
# 预期输出：编号：00042
print(f"编号：{idx:05d}")

# 科学计数法
big = 12300000000
# 预期输出：科学计数：1.230e+10
print(f"科学计数：{big:.3e}")


# ===== 5. 格式控制：对齐与宽度 =====
# 用途：打印整齐的表格。
#   <  左对齐     >  右对齐     ^  居中
#   数字跟在符号后面表示总宽度

print("---------- 5. 对齐与宽度 ----------")

# 左对齐宽度 8，再拼上数值
# 预期输出：苹果      | 12
print(f"{'苹果':<8}| {12}")
# 预期输出：香蕉      | 5
print(f"{'香蕉':<8}| {5}")
# 预期输出：大西瓜     | 30      （中文字符宽度按 1 计算，显示上会略窄）
print(f"{'大西瓜':<8}| {30}")

# 数字右对齐，方便看位数
# 预期输出：   1234
print(f"{1234:>7}")
# 预期输出：     12
print(f"{12:>7}")

# 居中
# 预期输出：[  标题  ]
print(f"[{'标题':^6}]")

# 居中的表头分隔线，效果直观
# 预期输出：  名称  |  数量     （实际宽度 = 一个中文按 1 个字符计算）
print(f"{'名称':^6}|{'数量':^6}")


# ===== 6. str.format()：老写法也要看懂 =====
# 语法：字符串里用 {} 占位，后面 .format(值1, 值2)。
# f-string 出现之前的主流写法，现在读旧代码经常遇到。

print("---------- 6. str.format() ----------")

# 位置参数，按顺序填入
# 预期输出：你好，小明！你今年 18 岁。
print("你好，{}！你今年 {} 岁。".format("小明", 18))

# 用编号指定顺序，可以重复使用同一个值
# 预期输出：18 岁的小明，小明已经 18 岁了
print("{1} 岁的{0}，{0}已经 {1} 岁了".format("小明", 18))

# 用关键字参数，可读性更好
# 预期输出：姓名：小红，城市：北京
print("姓名：{n}，城市：{c}".format(n="小红", c="北京"))

# 同样支持格式控制
# 预期输出：保留 2 位：3.14
print("保留 2 位：{:.2f}".format(3.14159))
# 预期输出：百分比：12.3%
print("百分比：{:.1%}".format(0.1234))
# 预期输出：居中对齐：[  中  ]
print("居中对齐：[{:^5}]".format("中"))

# 位置 + 关键字可以混用（位置参数必须在前）
# 预期输出：小明 考了 95 分
print("{} 考了 {s} 分".format("小明", s=95))


# ===== 7. % 格式化：更老的写法 =====
# 从 C 语言沿用下来的写法，维护老项目会见到，新代码建议用 f-string。

print("---------- 7. % 格式化（了解即可） ----------")

# %s 字符串，%d 整数，%f 浮点数
# 预期输出：小明 18 岁，身高 1.75 米
print("%s %d 岁，身高 %.2f 米" % ("小明", 18, 1.75))

# 百分号本身要用 %% 转义
# 预期输出：完成度 80%
print("完成度 %d%%" % 80)

# 左侧只有一个占位符时，括号可以省略
# 预期输出：得分：95
print("得分：%s" % 95)


# ===== 8. 字符串方法补充 =====
print("---------- 8. 常用字符串方法 ----------")

text = "  Hello Python  "

# strip() 去掉两端空格
# 预期输出：`Hello Python`
print(f"`{text.strip()}`")

# upper() / lower() 大小写转换
# 预期输出：HELLO PYTHON
print(text.strip().upper())
# 预期输出：hello python
print(text.strip().lower())

# replace() 替换
# 预期输出：Hello World
print("Hello Python".replace("Python", "World"))

# join() 用分隔符把列表拼成一个字符串
words = ["Python", "很", "有趣"]
# 预期输出：Python-很-有趣
print("-".join(words))

# 空字符串 join 等于直接连起来
# 预期输出：Python很有趣
print("".join(words))

# split() 按分隔符切成列表
# 预期输出：['a', 'b', 'c']
print("a,b,c".split(","))

# startswith / endswith 判断开头结尾
# 预期输出：以 Py 开头 → True
print("以 Py 开头 →", "Python".startswith("Py"))
# 预期输出：以 on 结尾 → True
print("以 on 结尾 →", "Python".endswith("on"))


# ===== 9. 综合小例子：打印一张成绩单 =====
print("---------- 9. 综合例子：成绩单 ----------")

students = [("小明", 92.5), ("小红", 88.0), ("小刚", 76.5)]

print(f"{'姓名':<6}{'分数':>8}{'等级':>6}")
print("-" * 20)

for stu_name, stu_score in students:
    # 用条件表达式算等级，用 f-string 控制对齐与小数位
    level = "A" if stu_score >= 90 else ("B" if stu_score >= 80 else "C")
    print(f"{stu_name:<6}{stu_score:>8.1f}{level:>6}")

# 预期输出（表格形式，见上面实际运行结果）：
# 姓名          分数    等级
# --------------------
# 小明        92.5     A
# 小红        88.0     B
# 小刚        76.5     C

# ---------- 小结 ----------
# 1. + 用于拼接（两边都要是字符串），* 用于重复（乘以整数）。
# 2. 字符串 + 数字必须用 str() 转换，或者直接用 f-string。
# 3. 格式化首选 f-string：f"{变量}"，花括号里能写表达式和格式控制。
# 4. 常用格式：.2f 保留小数、.1% 百分比、, 千分位、05d 补零、<^> 对齐。
# 5. str.format() 和 % 格式化是历史写法，看得懂、会查即可。
# 6. 别忘了 strip / replace / join / split 这些高频字符串方法。
