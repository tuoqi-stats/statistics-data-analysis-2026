# ============================================================
# 第 10 题：综合应用 —— 学生成绩单
# ------------------------------------------------------------
# 【思路】拆成 4 个小步骤，每步一个推导式，最后用循环 + f-string 排版。
#   1. 及格分数：筛选 stu[1] >= 60 后取 stu[1]
#   2. 等级：嵌套条件表达式，注意加括号
#   3. 人数统计：用 count() 数每个等级出现了几次
#   4. 排版：姓名 <6、分数 >4、等级 >4
# ============================================================
print("\n【第 10 题】综合应用 —— 学生成绩单")

students = [("小明", 92), ("小红", 78), ("小刚", 55), ("小美", 88)]

# ---- 步骤 1：及格的分数 ----
pass_scores = [s for _, s in students if s >= 60]
# 预期输出：及格的分数：[92, 78, 88]
print("及格的分数：", pass_scores)

# ---- 步骤 2：姓名 → 等级 ----
def to_level(score):
    """分数转等级（用嵌套条件表达式）"""
    return "A" if score >= 90 else ("B" if score >= 80 else ("C" if score >= 60 else "D"))

level_map = {name: to_level(score) for name, score in students}
# 预期输出：等级表：{'小明': 'A', '小红': 'C', '小刚': 'D', '小美': 'B'}
print("等级表：", level_map)

# ---- 步骤 3：各等级人数 ----
levels = list(level_map.values())
count_by_level = {lv: levels.count(lv) for lv in ("A", "B", "C", "D")}
# 预期输出：各等级人数：{'A': 1, 'B': 1, 'C': 1, 'D': 1}
print("各等级人数：", count_by_level)

# ---- 步骤 4：打印对齐的成绩单 ----
print("姓名      分数  等级")
print("-" * 22)
for name, score in students:
    level = level_map[name]
    # 注意：中文字符在等宽字体里占 2 个显示宽度，但 Python 按 1 个字符计算，
    # 所以靠 <6 对齐时，中文名会显得略宽一点，这是显示效果问题，不是 bug。
    print(f"{name:<6}{score:>4}{level:>4}")

# 实际输出（受中文宽度影响，中文名后面空隙看起来会少一些）：
# 姓名      分数  等级
# ----------------------
# 小明      92   A
# 小红      78   C
# 小刚      55   D
# 小美      88   B
#
# 💡 想让中文也严格对齐，可以用 str.center / 手动补空格，
#    或者把中文按 2 个宽度计算（进阶内容，本阶段不必纠结）。

# ---- 附加：平均分与通过率 ----
total = sum(score for _, score in students)
avg = total / len(students)
pass_rate = len(pass_scores) / len(students)

# 预期输出：总分：313，平均分：78.25
print(f"总分：{total}，平均分：{avg:.2f}")
# 预期输出：通过率：75.0%
print(f"通过率：{pass_rate:.1%}")

# 附加：按分数从高到低排序（用了 sorted + key，了解即可）
ranked = sorted(students, key=lambda item: item[1], reverse=True)
# 预期输出：排名：[('小明', 92), ('小美', 88), ('小红', 78), ('小刚', 55)]
print("排名：", ranked)

# 附加：一句话总结最高分
top_name, top_score = ranked[0]
# 预期输出：最高分：小明 92 分
print(f"最高分：{top_name} {top_score} 分")


