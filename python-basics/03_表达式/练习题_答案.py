# ============================================================
# 第 3 题：用括号表达意图
# ------------------------------------------------------------
# 【思路】原式 a + b / c * 2 里，b / c * 2 是同级左结合：
#         先算 b / c = 6 / 4 = 1.5，再 * 2 = 3.0，最后 a + 3.0 = 13.0
#         加括号写成 a + (b / c * 2) 后，运算顺序完全一样，
#         但读者一眼就能看出谁是整体。
# ============================================================
print("\n【第 3 题】用括号表达意图")

a, b, c = 10, 6, 4

# 原式
original = a + b / c * 2
# 预期输出：原式 = 13.0
print("原式 =", original)

# 加括号版本（明确表示 b / c * 2 是一个整体）
clear_version = a + (b / c * 2)
# 预期输出：加括号版本 = 13.0
print("加括号版本 =", clear_version)

# 预期输出：是否相等 → True
print("是否相等 →", clear_version == original)

# 补充：如果本意是"除以 (c * 2)"，就必须显式加括号，结果完全不同
another = a + b / (c * 2)
# 预期输出：如果写成 a + b / (c * 2) = 10.75
print("如果写成 a + b / (c * 2) =", another)


