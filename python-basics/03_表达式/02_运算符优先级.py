# -*- coding: utf-8 -*-
"""
02_运算符优先级.py —— 完整的优先级表、用括号明确意图

【本文件学什么】
  1. Python 运算符的完整优先级表（从高到低）
  2. 什么是"结合性"（左结合 / 右结合）
  3. 为什么"括号不是给 Python 看的，是给读代码的人看的"

【运行方式】
  在 VSCode 终端里执行：  python 02_运算符优先级.py

【预计输出】
  分节打印的优先级表和一组对比结果（加括号 vs 不加括号），
  1 秒内跑完，无需任何输入。
"""

# ===== 1. 优先级表（从高到低，数字越小越优先） =====
# 背不下来很正常！理解即可，写代码时靠括号。
#
# | 级别 | 运算符                                  | 说明                  |
# | ---- | --------------------------------------- | --------------------- |
# | 1    | ()  []  {}  .                           | 括号、下标、属性访问  |
# | 2    | **                                      | 幂（右结合）          |
# | 3    | +x  -x  ~x                              | 一元正负、按位取反    |
# | 4    | *  /  //  %                             | 乘除取余              |
# | 5    | +  -                                    | 加减                  |
# | 6    | <<  >>                                  | 移位                  |
# | 7    | &                                       | 按位与                |
# | 8    | ^                                       | 按位异或              |
# | 9    | |                                       | 按位或                |
# | 10   | ==  !=  >  <  >=  <=  in  is            | 比较                  |
# | 11   | not x                                   | 逻辑非                |
# | 12   | and                                     | 逻辑与                |
# | 13   | or                                      | 逻辑或                |
# | 14   | a if 条件 else b                        | 条件表达式            |
# | 15   | lambda                                  | 匿名函数              |
# | 16   | =  +=  -=  ...                          | 赋值（最低）          |
#
# 💡 记忆口诀：
#    算术 > 比较 > not > and > or > 条件表达式 > 赋值
#    括号里最优先，幂运算比其他算术都高。

print("---------- 1. 优先级表速查 ----------")
print("算术 > 比较 > not > and > or > 条件表达式 > 赋值")
print("括号 () 优先级最高，赋值 = 最低")


# ===== 2. 括号最高 vs 一元负号 =====
print("---------- 2. 括号与一元负号 ----------")

# 括号最高，先算括号里的
# 预期输出：(2 + 3) * 4 = 20
print("(2 + 3) * 4 =", (2 + 3) * 4)

# 不加括号时乘法优先，先算 3 * 4
# 预期输出：2 + 3 * 4 = 14
print("2 + 3 * 4 =", 2 + 3 * 4)

# 一元负号的优先级比乘法低、比幂高，容易踩坑
# -2 ** 2 会先算 2 ** 2，再取负
# 预期输出：-2 ** 2 = -4
print("-2 ** 2 =", -2 ** 2)

# (-2) ** 2 才是负二的平方
# 预期输出：(-2) ** 2 = 4
print("(-2) ** 2 =", (-2) ** 2)


# ===== 3. 幂运算是"右结合" =====
# 结合性决定同优先级运算符从哪边算起。
# 算术运算符大多是"左结合"（从左往右），但 ** 是"右结合"（从右往左）。

print("---------- 3. 右结合：幂运算 ----------")

# 2 ** 3 ** 2 等价于 2 ** (3 ** 2) = 2 ** 9 = 512
# 预期输出：2 ** 3 ** 2 = 512
print("2 ** 3 ** 2 =", 2 ** 3 ** 2)

# 如果从左往右算会是 (2 ** 3) ** 2 = 64，显然不是上面的结果
# 预期输出：强制左结合 (2 ** 3) ** 2 = 64
print("强制左结合 (2 ** 3) ** 2 =", (2 ** 3) ** 2)

# 减法是左结合：10 - 3 - 2 等价于 (10 - 3) - 2 = 5
# 预期输出：10 - 3 - 2 = 5
print("10 - 3 - 2 =", 10 - 3 - 2)


# ===== 4. 算术 vs 比较 =====
# 比较运算符优先级低于算术，所以两边会先算完再比较。

print("---------- 4. 算术 > 比较 ----------")

# 先算 1 + 1 = 2，再比较 2 == 2
# 预期输出：1 + 1 == 2 → True
print("1 + 1 == 2 →", 1 + 1 == 2)

# 先算 2 * 3 = 6，再比较 6 > 5
# 预期输出：2 * 3 > 5 → True
print("2 * 3 > 5 →", 2 * 3 > 5)

# 先算 6 % 4 = 2，再比较 2 != 0
# 预期输出：6 % 4 != 0 → True
print("6 % 4 != 0 →", 6 % 4 != 0)


# ===== 5. not / and / or 的顺序 =====
# 顺序是 not > and > or。这个如果不清楚，逻辑判断很容易写错。

print("---------- 5. not > and > or ----------")

# 先算 not True 得 False，再算 False and False
# 预期输出：not True and False → False
print("not True and False →", not True and False)

# and 优先于 or：先算 True and False 得 False，再算 True or False
# 预期输出：True or True and False → True
print("True or True and False →", True or True and False)

# 加括号就变成先算 or：True or True 得 True，再 True and False
# 预期输出：(True or True) and False → False
print("(True or True) and False →", (True or True) and False)

# 用括号表达"先算 or"的意图，结果完全不同
# 预期输出：(False or True) and False → False
print("(False or True) and False →", (False or True) and False)
# 预期输出：False or (True and False) → False
print("False or (True and False) →", False or (True and False))


# ===== 6. 比较 vs 逻辑 =====
print("---------- 6. 比较 > not > and > or ----------")

# 先算两个比较，再算 and
# 预期输出：1 < 2 and 3 > 2 → True
print("1 < 2 and 3 > 2 →", 1 < 2 and 3 > 2)

# not 作用于它右边紧邻的比较结果
# 预期输出：not 1 > 2 → True
print("not 1 > 2 →", not 1 > 2)

# 不加括号时的真实运算顺序（and 先）：
# 预期输出：False and True or True → True
print("False and True or True →", False and True or True)


# ===== 7. 条件表达式的位置 =====
# 条件表达式的优先级比 or 还低，所以放在赋值语句右边很安全。

print("---------- 7. 条件表达式位置 ----------")

score = 75

# 先算条件 score >= 60，再决定取哪个值
# 预期输出：及格状态 = 及格
print("及格状态 =", "及格" if score >= 60 else "不及格")

# 注意：不能把条件表达式当条件用，下面这种要加括号才不歧义
# 预期输出：判定 = 60 分以上
print("判定 =", "60 分以上" if score > 60 else ("刚好 60" if score == 60 else "60 分以下"))


# ===== 8. 用括号明确意图（重点） =====
# 同一个数学式子可以写成多种形式，选"一眼看懂"的那种。

print("---------- 8. 括号让意图清晰 ----------")

a, b, c = 10, 6, 4

# 写法一：靠优先级硬算，读者要回忆优先级
# 先算 b / c * 2 = 6 / 4 * 2 = 3.0，再 a + 3.0 + 1 = 14.0
# 预期输出：难懂写法 = 14.0
print("难懂写法 =", a + b / c * 2 + 1)

# 写法二：加括号，一眼看出谁先算
# 预期输出：清晰写法 = 14.0
print("清晰写法 =", a + (b / c * 2) + 1)

# 两个结果一样，但第二种更好维护
# 预期输出：两种写法结果相同 → True
print("两种写法结果相同 →", (a + b / c * 2 + 1) == (a + (b / c * 2) + 1))

# 复杂逻辑判断尤其需要括号
age = 20
has_ticket = True

# 预期输出：能否入场 → True
print("能否入场 →", (age >= 18) and (has_ticket is True))


# ===== 9. 赋值是最低优先级 =====
print("---------- 9. 赋值最低 ----------")

# 右边全算完才赋值给左边
result = 2 + 3 * 4
# 预期输出：result = 14
print("result =", result)

# 增强赋值也是先用"右边表达式"和"左旧值"算出新值
counter = 10
counter += 5 * 2      # 等价于 counter = counter + (5 * 2) = 10 + 10
# 预期输出：counter = 20
print("counter =", counter)


# ===== 10. 优先级速查实验 =====
print("---------- 10. 几个易混对比 ----------")

# 移位高于按位与：先算 1 << 2 得 4，再 4 & 4 得 4
# 预期输出：1 << 2 & 4 = 4
print("1 << 2 & 4 =", 1 << 2 & 4)

# 按位与高于按位异或：先算 4 & 6 得 4，再 4 ^ 1 得 5
# 预期输出：4 & 6 ^ 1 = 5
print("4 & 6 ^ 1 =", 4 & 6 ^ 1)

# 成员运算符和比较同级，从左到右
# 预期输出：3 in [1, 2, 3] → True
print("3 in [1, 2, 3] →", 3 in [1, 2, 3])

# ---------- 小结 ----------
# 1. 优先级顺序：括号 > 幂 > 一元正负 > 乘除 > 加减 > 移位 > 按位 > 比较 > not > and > or > 条件表达式 > 赋值。
# 2. 结合性：多数运算符左结合；** 是右结合（2 ** 3 ** 2 = 512）。
# 3. -2 ** 2 是 -4，(-2) ** 2 是 4，一元负号比幂的优先级低。
# 4. 算术 > 比较 > not > and > or 这条主线一定要记牢。
# 5. ⚠️ 最实用的建议：记不住优先级就加括号，括号是给读代码的人看的。
