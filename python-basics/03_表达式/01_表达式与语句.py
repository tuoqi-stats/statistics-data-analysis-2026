# -*- coding: utf-8 -*-
"""
01_表达式与语句.py —— 什么是表达式、表达式求值、表达式 vs 语句

【本文件学什么】
  1. 表达式（expression）到底是什么：有值、能求值
  2. 表达式求值的过程：Python 是怎么一步步算出来的
  3. 表达式和语句（statement）的区别：一个"有值"，一个"做事"

【运行方式】
  在 VSCode 终端里执行：  python 01_表达式与语句.py

【预计输出】
  一片分节的文字说明 + 每个表达式的计算结果，
  全部是打印出来的，不会有任何输入等待，1 秒内跑完。
"""

# ===== 1. 什么是表达式 =====
# 表达式 = 一段"能算出值"的代码。
# 通俗类比：表达式就像一道算术题，写完就有一个答案。
# 最小的表达式甚至就是一个数字或一个字符串。

print("---------- 1. 最小的表达式 ----------")

# 单独一个数字就是一个表达式，它的值就是它自己
# 预期输出：5
print(5)

# 单独一个字符串也是表达式
# 预期输出：hello
print("hello")

# 用一个变量记住一个表达式的值
number = 5
# 预期输出：5
print(number)


# ===== 2. 表达式求值：Python 是怎么算的 =====
# "求值"就是算出表达式的值。复杂表达式是按"优先级 + 从左到右"逐步算出来的。
# 以 price * count + 5 为例，如果 price=10、count=3：
#   第 1 步：先算 price * count  →  10 * 3 = 30   （乘法比加法优先）
#   第 2 步：再算 30 + 5         →  35
#   第 3 步：得到整个表达式的值   →  35

print("---------- 2. 表达式求值过程 ----------")

price = 10
count = 3

# 预期输出：10 * 3 = 30
print("第一步：10 * 3 =", price * count)

# 预期输出：30 + 5 = 35
print("第二步：30 + 5 =", price * count + 5)

# 把整个表达式的值交给变量 total
total = price * count + 5
# 预期输出：整个表达式的值 = 35
print("整个表达式的值 =", total)


# ===== 3. 各种类型的表达式 =====
# 表达式的值可以是不同类型：数字、字符串、布尔值、列表……

print("---------- 3. 各种类型的表达式 ----------")

# 算术表达式，值是数字
# 预期输出：7 + 3 = 10
print("7 + 3 =", 7 + 3)

# 比较表达式，值是布尔值（True / False）
# 预期输出：7 > 3 = True
print("7 > 3 =", 7 > 3)

# 字符串表达式，值是字符串
# 预期输出：姓名 = 小明
print("姓名 =", "小" + "明")

# 用 type() 查看一个表达式的值是什么类型
# 预期输出：10 的类型 = <class 'int'>
print("10 的类型 =", type(7 + 3))
# 预期输出：True 的类型 = <class 'bool'>
print("True 的类型 =", type(7 > 3))
# 预期输出：3.5 的类型 = <class 'float'>
print("3.5 的类型 =", type(7 / 2))


# ===== 4. 表达式 vs 语句 =====
# 判断口诀：能不能放在 print() 里？
#   能放进 print() 的，就是表达式（因为它有值）。
#   不能放进去的，就是语句（因为它只是"做一件事"，没有值）。

print("---------- 4. 表达式 vs 语句 ----------")

# 表达式可以塞进 print() 里
# 预期输出：可以放进来：30
print("可以放进来：", 10 * 3)

# 语句不能塞进 print() 里，下面这行会报语法错误，所以用注释演示：
# print(x = 10)          # SyntaxError：赋值语句不能当表达式用

# 但赋值语句右边的部分必须是表达式
x = 10 * 3   # ← 这是一个赋值语句；右边的 10 * 3 是表达式
# 预期输出：x = 30
print("x =", x)

# 再看几个"语句"的例子（它们都只是做事，本身没有值）
#   import math          导入模块，是语句
#   def f(): pass        定义函数，是语句
#   if x > 0: pass       条件判断，是语句
#   for i in range(3):   循环，是语句


# ===== 5. 表达式可以作为参数和返回值 =====
# 因为表达式有值，所以可以当作函数的参数传进去、
# 也可以直接作为函数的返回值返回。

print("---------- 5. 表达式作为参数和返回值 ----------")

# 表达式作为参数传进去
# 预期输出：最大值 = 20
print("最大值 =", max(10 + 10, 5 * 3))

# 表达式作为函数的返回值
def average(a, b):
    """返回 a 和 b 的平均值（返回值本身就是一个表达式）"""
    return (a + b) / 2

# 预期输出：平均值 = 15.0
print("平均值 =", average(10, 20))

# 表达式的值可以继续参与运算，套娃也没问题
# 预期输出：套娃结果 = 25.0
print("套娃结果 =", average(10, 20) + 10)


# ===== 6. 一行里塞多个表达式 =====
print("---------- 6. 一行写多个表达式 ----------")

# 用逗号分隔，print 会把它们用空格连起来输出
# 预期输出：1 2 3
print(1, 2, 3)

# 每个位置都可以是复杂表达式
# 预期输出：和=11 差=5 积=24
print("和=" + str(8 + 3), "差=" + str(8 - 3), "积=" + str(8 * 3))

# 用 sep 参数自定义分隔符
# 预期输出：2026-9-24
print(2026, 9, 24, sep="-")


# ===== 7. 表达式也有"副作用"的例外 =====
# 严格来说函数调用（如 print(...)）既是表达式又有副作用，
# 但初学阶段记住主结论就够了：
#   算术/比较/字符串拼接  →  表达式，有值
#   赋值/if/for/def/import  →  语句，做事

print("---------- 7. 一句话总结 ----------")
print("表达式有值，语句做事。判断方法：能不能放进 print() 里。")

# ---------- 小结 ----------
# 1. 表达式 = 能算出值的代码片段，最小可以只是一个数字或字符串。
# 2. 表达式求值遵循"优先级 + 从左到右"，复杂表达式是一步步算出来的。
# 3. 表达式 vs 语句的判断口诀：能放进 print() 里的是表达式，不能的是语句。
# 4. 表达式因为有值，所以能当函数参数、能当返回值、能继续参与运算。
# 5. 赋值语句 = 变量 + "=" + 表达式，右边的部分永远是表达式。
